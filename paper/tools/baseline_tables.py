"""Write the paper's simulation and forecast tables from the v4 baseline report.

This supports the endpoints and test periods in analysis plan sections 1 and 2.
Use the report's core-well medians and model labels so the tables and the
commands used in the text agree. Choose the best Chronos-2 variant at each
horizon before rounding its score. No model is fitted for this build.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/baseline_tables.py [--out DIR]
"""
import argparse
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
if not __package__:
    sys.path.insert(0, str(ROOT))

from paper.tools.kg_tables import num, row, tex_escape
from src.analysis import baseline_report
from src.config import DATASET, TEST_PERIODS

OUT = ROOT / "paper" / "tables"
COMMAND = "PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/baseline_tables.py"
SOURCE = "src/analysis/baseline_report.py:main_table()"
HEADER = f"% Generated by {COMMAND}\n% Sources: {SOURCE}, src/config.py:TEST_PERIODS"
REFERENCE_TAG = " [reference]"
HORIZONS = {4: "Four", 12: "Twelve"}
PHASE_METRICS = ("NSE drought", "skill drought", "NSE recovery", "skill recovery")
PHASE_HEADINGS = (r"\shortstack{NSE\\drought}", r"\shortstack{Skill\\drought}",
                  r"\shortstack{NSE\\recovery}", r"\shortstack{Skill\\recovery}")


def period_text(period):
    first, last = TEST_PERIODS[period]
    return f"{first} to {last or 'end of record'}"


def number_cell(value, decimals=2):
    return r"\textemdash{}" if math.isnan(value) else num(f"{value:.{decimals}f}")


def table(kind, caption, columns, headings, rows):
    lines = [HEADER, r"\begin{table}[p]", r"\centering", r"\scriptsize",
             r"\setlength{\tabcolsep}{3pt}", rf"\caption{{{caption}}}",
             rf"\label{{tab:baselines-{kind}}}", rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
             r"\toprule", row(*headings), r"\midrule", *rows,
             r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def simulation_table(simulation, reference, periods):
    rows = [
        row(tex_escape(entry["model"].removesuffix(REFERENCE_TAG)),
            *(number_cell(entry[metric]) for metric in (*PHASE_METRICS, "KGE'' test")),
            number_cell(entry["wells"], 0))
        for _, entry in simulation.iterrows()
    ]
    caption = (f"Simulation baseline medians over the 33 core wells. {periods} "
               "Skill is relative to the training climatology. "
               f"The hydrology reference is {tex_escape(reference.removesuffix(REFERENCE_TAG))}.")
    headings = ("Model", *PHASE_HEADINGS, r"\shortstack{KGE$''$\\test}", "Wells")
    return table("simulation", caption, r"p{0.44\linewidth}rrrrrr", headings, rows)


def forecast_table(forecast, periods):
    rows = [
        row(number_cell(entry["h"], 0), tex_escape(entry["model"]),
            *(number_cell(entry[metric]) for metric in PHASE_METRICS),
            number_cell(entry["wells"], 0))
        for _, entry in forecast.iterrows()
    ]
    caption = (f"Forecast baseline medians over the 33 core wells. {periods} "
               "Skill is relative to anomaly persistence at the same horizon.")
    headings = (r"\shortstack{Horizon\\(weeks)}", "Model", *PHASE_HEADINGS, "Wells")
    return table("forecast", caption, r"rp{0.37\linewidth}rrrrr", headings, rows)


def number_macros(simulation, forecast, reference):
    """Record the report row and column beside each command."""
    lines = [HEADER]
    forecast_labels = dict(baseline_report.FC)
    chronos = [label for run, label in baseline_report.FC if run.startswith("chronos2")]
    for horizon, suffix in HORIZONS.items():
        models = forecast.loc[forecast["h"] == horizon].set_index("model")
        best = models.loc[chronos, "NSE drought"].idxmax()
        source = f"{SOURCE}, forecast, {horizon} weeks"
        lines.append(rf"\newcommand{{\baselineChronos{suffix}Variant}}{{{tex_escape(best)}}}"
                     f" % {source}, model with maximum drought NSE")
        for name, model in (("Chronos", best), ("LightGBM", forecast_labels["lgbm_fc"]),
                            ("AnomalyPersistence", forecast_labels["naive_anomaly_persist"])):
            value = number_cell(models.at[model, "NSE drought"])
            lines.append(rf"\newcommand{{\baseline{name}{suffix}DroughtNSE}}{{{value}}}"
                         f" % {source}, {model}, NSE drought")

    simulation_labels = dict(baseline_report.SIM)
    models = simulation.set_index("model")
    for name, model in (("Pastas", reference), ("LSTM", simulation_labels["lstm_tuned"]),
                        ("DistanceSTGNN", simulation_labels["stgnn_tuned"]),
                        ("Ensemble", simulation_labels["ensemble_sim"])):
        for metric, suffix in (("NSE drought", "NSE"), ("skill drought", "Skill")):
            value = number_cell(models.at[model, metric])
            lines.append(rf"\newcommand{{\baseline{name}Drought{suffix}}}{{{value}}}"
                         f" % {SOURCE}, simulation, {model}, {metric}")
    return "\n".join(lines) + "\n"


def generate(out=OUT):
    """Prepare the three fragments before writing any of them."""
    if DATASET != "v4":
        raise ValueError("The paper baseline tables require PFE_DATASET=v4")
    main_table = baseline_report.main_table()
    simulation = main_table.loc[(main_table["task"] == "simulation") & (main_table["h"] == 0)]
    forecast = main_table.loc[(main_table["task"] == "forecast") & main_table["h"].isin(HORIZONS)]
    reference = simulation.loc[simulation["model"].str.endswith(REFERENCE_TAG), "model"].item()
    periods = (f"Drought covers {period_text('test_drought')}. "
               f"Recovery covers {period_text('test_recovery')}.")
    documents = {
        "baselines_simulation.tex": simulation_table(simulation, reference, periods),
        "baselines_forecast.tex": forecast_table(forecast, periods),
        "baselines_numbers.tex": number_macros(simulation, forecast, reference),
    }
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, content in documents.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {out / name}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT, help="output folder (default: paper/tables)")
    args = parser.parse_args(argv)
    generate(args.out)


if __name__ == "__main__":
    main()
