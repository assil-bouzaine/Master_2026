"""Check the real-data shortcut test 2 statistic and its report.

    PFE_DATASET=v4 python -m tests.test_seed_disagreement
"""

from pathlib import Path
from tempfile import TemporaryDirectory

import numpy as np
import pandas as pd

from src.analysis import seed_disagreement as S
from src.analysis import twin_report
from src.analysis.ladder_report import per_well
from src.config import RESULTS_DIR


def test_synthetic():
    train = pd.DatetimeIndex(["2019-12-22", "2019-12-29"])
    drought = pd.date_range("2022-05-01", periods=25, freq="W-SUN").append(
        pd.DatetimeIndex(["2025-11-23", "2025-11-30"]))
    outside = pd.DatetimeIndex(["2004-12-26", "2020-01-05", "2022-04-24", "2025-12-07"])
    weeks = train.append([drought, outside])
    offsets = {"well_a": [(0, 0), (3, 4), (0, 4)], "well_b": [(0, 0), (0, 12), (12, 12)]}
    panel = pd.concat([pd.DataFrame({"code_bss": well, "week": weeks, "core": True, "sd": sd,
                                    "head": np.where(weeks == drought[0], np.nan, 1.0),
                                    "split": np.where(weeks.isin(train), "train", "other")})
                       for well, sd in (("well_a", 2.0), ("well_b", 4.0))], ignore_index=True)

    with TemporaryDirectory() as tmp:
        run = Path(tmp)
        panel.to_parquet(run / "panel.parquet", index=False)
        for k in range(3):
            parts = []
            for i, (well, start_offsets) in enumerate(offsets.items()):
                mean = -100.0 - 25 * k - 5 * i
                total = np.full(len(weeks), mean)
                total[:2] += [-2, 2]
                total[[2, 2 + len(drought) - 1]] += start_offsets[k]
                total[-4:] -= 1000 * k
                frame = pd.DataFrame({"code_bss": well, "week": weeks, "pumping": total})
                if k != 0:
                    frame["pumping"] = total * 0.25
                    frame["pumping_unattributed"] = total * 0.75
                parts.append(frame)
            pd.concat(parts).iloc[::-1].to_parquet(run / f"contrib_seed_{k}.parquet", index=False)
        sd, train_weeks, drought_weeks = S.panel_inputs(run / "panel.parquet")
        np.testing.assert_array_equal(train_weeks, train)
        np.testing.assert_array_equal(drought_weeks, drought)
        pairs = S.pair_disagreements(run, sd, train_weeks, drought_weeks, starts=(0, 1, 2))

    # Only the first and last of the 27 drought weeks can differ after centring.
    # The first has no observed head, so the test also checks that the RMSE uses it.
    root_n = np.sqrt(27)
    expected = np.array([[2.5, 2.0, 1.5], [3.0, 3.0 * np.sqrt(2), 3.0]]) / root_n
    np.testing.assert_allclose(pairs.to_numpy(), expected)
    medians = pairs.median()
    np.testing.assert_allclose(medians[0, 1], 5.5 / (2 * root_n))
    np.testing.assert_allclose(medians.mean(), (12 + 3 * np.sqrt(2)) / (6 * root_n))
    print(f"  1. synthetic run: 2 core wells, 3 pairs, starts 0–1 {medians[0, 1]:.6f}, "
          f"all-pairs mean {medians.mean():.6f}")


def test_real():
    run = RESULTS_DIR / "resp_pooled_l001"
    inputs = S.panel_inputs(RESULTS_DIR / "_cache" / "panel.parquet")
    pairs = S.pair_disagreements(run, *inputs)
    core = per_well(pd.read_csv(run / "metrics_per_well.csv")).index
    assert set(pairs.index) == set(core) and len(core) > 0
    assert pairs.shape[1] == 45
    assert np.isfinite(pairs.to_numpy()).all() and (pairs[0, 1] > 0).all()
    medians = pairs.median()
    print(f"  2. {run.name}: {len(pairs)} core wells, starts 0–1 {medians[0, 1]:.6f}, "
          f"all-pairs mean {medians.mean():.6f}")


def test_render():
    grid = twin_report.load({twin_report.GRID_RUN})
    with TemporaryDirectory() as tmp:
        path = Path(tmp) / "results_seed_disagreement_v4.md"
        S.write_report(path, RESULTS_DIR, grid)
        report = path.read_text(encoding="utf-8")
    assert "Generated by `python -m src.analysis.seed_disagreement`" in report
    assert "**uncalibrated**" in report and "slice F" in report
    assert "| `resp_pooled_l001` | pooled λ = 0.01, early stopping |" in report
    for name in S.RUNS:
        assert report.count(f"| `{name}` |") == 1
    for arm in ("C", "D"):
        for setting in twin_report.PROTOCOLS:
            assert f"| {arm} | `{setting}` |" in report
    print(f"  3. rendered {len(S.RUNS)} real-data rows and 4 twin grid rows into a temporary file")


if __name__ == "__main__":
    test_synthetic()
    test_real()
    test_render()
    print("test_seed_disagreement: all checks passed")
