"""Usage audit of the lulcw terms: which terms does anything use? (fable_review.md §7)

    PFE_DATASET=v4 python -m src.kg.term_usage     # -> docs/ontology_term_usage.md

For every term declared in ontology/lulcw.ttl: the number of triples of the validated graph release
(facts and rule outputs) that use it as a predicate, as a class (object of rdf:type) or as another
object; and whether the SHACL-AF rules, the SHACL shapes, the competency-question queries
(tests/cq/*.rq), the alignment modules or the ontology's own axioms (domain, range, subclass,
scheme membership) mention it. A term used by none of these is a candidate for removal; a term the
data never use but a rule, a shape or a query names is declared for a case the data do not contain
yet (or for a fixture). Also the terms each competency question's queries name: the traceability
from requirement to vocabulary that the methodology asks for (LOT, Poveda-Villalón et al. 2022,
doi:10.1016/j.engappai.2022.104755). The audit reports; it removes nothing (the ontology is
feature-frozen at 0.7.x, analysis plan §14 item 18).
"""
import re
from collections import Counter, defaultdict

import rdflib
from rdflib.namespace import OWL, RDF, RDFS, SKOS

from src.config import DATASET, ROOT
from src.kg import release
from src.kg.cq import CQ, kg_store

L = "https://w3id.org/lulcw#"
ONTO = ROOT / "ontology"
KIND = ((OWL.Class, "class"), (OWL.ObjectProperty, "object property"),
        (OWL.DatatypeProperty, "datatype property"), (SKOS.ConceptScheme, "concept scheme"))


def declared():
    """{local name: kind}; individuals (concepts of the schemes) are "individual"."""
    g = rdflib.Graph().parse(ONTO / "lulcw.ttl")
    out = {}
    for s in {s for s in g.subjects(RDF.type, None) if str(s).startswith(L)}:
        types = set(g.objects(s, RDF.type))
        out[str(s)[len(L):]] = next((name for t, name in KIND if t in types), "individual")
    structural = Counter()
    for s, p, o in g:
        if p in (RDF.type, RDFS.label, SKOS.prefLabel, SKOS.definition, RDFS.comment):
            continue
        for x in (p, o):
            if isinstance(x, rdflib.URIRef) and str(x).startswith(L) and x != s:
                structural[str(x)[len(L):]] += 1
    return out, structural


def data_counts(store):
    pre = "PREFIX lulcw: <https://w3id.org/lulcw#> "
    q = {"predicate": "SELECT ?t (COUNT(*) AS ?n) WHERE { ?s ?t ?o } GROUP BY ?t",
         "class": "SELECT ?t (COUNT(*) AS ?n) WHERE { ?s a ?t } GROUP BY ?t",
         "object": "SELECT ?t (COUNT(*) AS ?n) WHERE { ?s ?p ?t FILTER (isIRI(?t) && ?p != "
                   "<http://www.w3.org/1999/02/22-rdf-syntax-ns#type>) } GROUP BY ?t"}
    out = defaultdict(Counter)
    for role, query in q.items():
        for t, n in store.query(pre + query):
            if t.value.startswith(L):
                out[t.value[len(L):]][role] = int(n.value)
    return out


def mentions(files):
    """{local name: number of files among `files` that write lulcw:<name>}."""
    c = Counter()
    for f in files:
        c.update(set(re.findall(r"lulcw:([A-Za-z_][A-Za-z0-9_]*)", f.read_text(encoding="utf-8"))))
    return c


def main():
    m = release.check()
    terms, structural = declared()
    data = data_counts(kg_store())
    where = {"rules": mentions([ONTO / "rules" / "lulcw-rules.ttl"]),
             "shapes": mentions([ONTO / "shapes" / "lulcw-shapes.ttl"]),
             "queries": mentions(sorted(CQ.glob("*.rq"))),
             "alignments": mentions(sorted((ONTO / "alignments").glob("*.ttl")))}
    rows = []
    for t, kind in sorted(terms.items()):
        n_data = sum(data[t].values())
        used_by = [k for k, c in where.items() if c[t]]
        status = ("in the data" if n_data else "rules, shapes or queries only" if used_by
                  else "ontology axioms only" if structural[t] else "unused")
        rows.append((t, kind, n_data, used_by, status))
    kinds = [name for _, name in KIND] + ["individual"]
    statuses = ["in the data", "rules, shapes or queries only", "ontology axioms only", "unused"]
    tab = Counter((k, s) for _, k, _, _, s in rows)
    by_cq = defaultdict(set)
    for f in sorted(CQ.glob("*.rq")):
        by_cq[f.stem.split("_")[0].upper()] |= set(re.findall(r"lulcw:([A-Za-z_][A-Za-z0-9_]*)", f.read_text()))
    L_ = [f"# Usage of the lulcw terms (generated)\n\nGenerated by `python -m src.kg.term_usage` (dataset "
          f"**{DATASET}**, graph release of {m['released']}); do not edit by hand. {len(rows)} terms declared "
          "in `ontology/lulcw.ttl`. \"In the data\" = at least one triple of the facts or of the rule outputs "
          "uses the term (as a predicate, a class or another object). The audit reports; it removes nothing.\n",
          "## Summary\n",
          "| kind | " + " | ".join(statuses) + " | total |\n|---|" + "---:|" * (len(statuses) + 1),
          *[f"| {k} | " + " | ".join(str(tab[(k, s)]) for s in statuses)
            + f" | {sum(tab[(k, s)] for s in statuses)} |" for k in kinds],
          "| **all** | " + " | ".join(f"**{sum(tab[(k, s)] for k in kinds)}**" for s in statuses)
          + f" | **{len(rows)}** |\n"]
    for s, title, note in (
            ("unused", "Terms nothing uses",
             "Not in the data, the rules, the shapes, the queries, the alignments or another term's axioms: "
             "candidates for removal, or terms of a module whose data are still to come."),
            ("ontology axioms only", "Terms only other terms' axioms use",
             "Named by a domain, a range, a superclass or a scheme, never by data, a rule, a shape or a query "
             "(for example a superclass that only organises its subclasses)."),
            ("rules, shapes or queries only", "Terms the data never use but a rule, a shape or a query names",
             "Declared for a case the released data do not contain (or only the fixtures do).")):
        sel = [(t, k, u) for t, k, _, u, st in rows if st == s]
        L_ += [f"## {title} ({len(sel)})\n\n{note}\n",
               "| term | kind | named by |\n|---|---|---|",
               *[f"| `{t}` | {k} | {', '.join(u) or '—'} |" for t, k, u in sel], ""]
    L_ += ["## Terms named by each competency question's queries\n",
           "| CQ | query files | lulcw terms named | of which never in the data |\n|---|---:|---:|---|"]
    never = {t for t, _, n, _, _ in rows if not n}
    for cq, ts in sorted(by_cq.items(), key=lambda kv: int(kv[0][2:])):
        ts &= set(terms)
        L_.append(f"| {cq} | {len(list(CQ.glob(cq.lower() + '_*.rq')))} | {len(ts)} | "
                  f"{', '.join('`' + t + '`' for t in sorted(ts & never)) or '—'} |")
    named = set().union(*by_cq.values()) & set(terms)
    L_.append(f"\n{len(named)} of the {len(rows)} terms are named by at least one query; the others are "
              "reached through the rules and shapes, or describe provenance and evidence that the queries "
              "return without naming.\n")
    out = ROOT / "docs" / "ontology_term_usage.md"
    out.write_text("\n".join(L_))
    print({s: sum(tab[(k, s)] for k in kinds) for s in statuses}, "->", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
