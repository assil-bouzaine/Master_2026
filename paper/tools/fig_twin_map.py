"""Draw the twin's knowledge-value map and write the numbers for paper section 6.1.

Read the saved base grid and compare the graph and the oracle with the distance
arm, as in analysis plan section 14, item 19. The third column shows how often
the graph recovered pumping better than the distance arm in the same world.
The command writes the figure to paper/figures and twin_numbers.tex to
paper/tables. With --out, both go to that directory unless --tables-out is set.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/fig_twin_map.py [--out DIR] [--tables-out DIR]
"""
import argparse
from pathlib import Path
import sys

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import Normalize
from matplotlib.patches import Rectangle
from matplotlib.ticker import FormatStrFormatter, PercentFormatter

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.analysis.twin_report import PAYS, PLANNED_WORLDS, PROTOCOLS, RESULTS, _q, load
from src.config import ROOT

OUT = ROOT / "paper" / "figures"
TABLES_OUT = ROOT / "paper" / "tables"
DIALS = ["dial_eps", "dial_u"]
EPS = (0, 0.1, 0.25, 0.5)
U = (0, 0.3, 0.6)
SHAPE = (len(EPS), len(U))
ROW_LABELS = ("Early stopping", "Converged pooling")
D_OVER_C = "log_rmse_D_over_C"
T_OVER_C = "log_rmse_T_over_C"
PUMP_D, PUMP_C = "recovery_pumping_D", "recovery_pumping_C"
INK = "#263444"


def summarize_worlds(worlds):
    """Make one grid per statistic, in the same dial order as the axes."""
    grid = pd.MultiIndex.from_product((EPS, U), names=DIALS)
    results, pays_cells = {}, {}
    for setting in PROTOCOLS:
        rows = worlds.loc[worlds["setting"].eq(setting)]
        by_cell = rows.groupby(DIALS)
        counts = by_cell["world"].agg(["size", "nunique"])
        if set(counts.index) != set(grid) or not counts.eq(PLANNED_WORLDS).all().all():
            raise ValueError(f"{setting} must have {PLANNED_WORLDS} different worlds in each grid cell")
        if not np.isfinite(rows[[D_OVER_C, T_OVER_C, PUMP_D, PUMP_C]].to_numpy(dtype=float)).all():
            raise ValueError(f"{setting} has missing or non-finite scores")

        medians = by_cell[[D_OVER_C, T_OVER_C]].median().reindex(grid)
        upper_d = by_cell[D_OVER_C].quantile(0.975).reindex(grid)
        pays = medians[D_OVER_C].le(PAYS) & upper_d.lt(0)
        wins = rows[PUMP_D].lt(rows[PUMP_C]).groupby([rows[dial] for dial in DIALS]).mean()
        results[setting] = {
            D_OVER_C: medians[D_OVER_C].to_numpy().reshape(SHAPE),
            T_OVER_C: medians[T_OVER_C].to_numpy().reshape(SHAPE),
            "pumping_recovery_share": wins.reindex(grid).to_numpy().reshape(SHAPE),
            "pays_count": int(pays.sum()),
        }
        pays_cells[setting] = pays.to_numpy().reshape(SHAPE)
    return results, pays_cells


def compare_protocols(worlds):
    """Apply rule (e) to worlds evaluated under both protocols in each cell."""
    free, pooled = PROTOCOLS
    free_wins, nse_differences = 0, []
    for _, cell in worlds.groupby(DIALS):
        early = cell.loc[cell["setting"].eq(free)].set_index("world")
        converged = cell.loc[cell["setting"].eq(pooled)].set_index("world")
        paired = early.index.intersection(converged.index)
        if paired.empty:
            continue
        early = early.loc[paired]
        converged = converged.loc[paired]
        free_wins += int(early[PUMP_D].median() < converged[PUMP_D].median())
        nse_differences.append(early["nse_drought_D"].median() - converged["nse_drought_D"].median())
    if not nse_differences or not np.isfinite(nse_differences).all():
        raise ValueError("The paired protocol comparison has missing drought NSE")
    return free_wins, len(nse_differences), float(np.median(nse_differences))


def number_macros(worlds, results):
    """Generate numbers with a source comment on every definition."""
    source = RESULTS / "twin_map"
    if source.is_relative_to(ROOT):
        source = source.relative_to(ROOT)
    worlds_path = f"{source}/<cell>/world_*.json"
    lines = ["% Generated by PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/fig_twin_map.py"]
    for suffix, setting in zip(("Free", "Pooled"), PROTOCOLS):
        rows = worlds.loc[worlds["setting"].eq(setting)]
        result = results[setting]
        dc, tc = result[D_OVER_C], result[T_OVER_C]
        high = rows.groupby(DIALS)[D_OVER_C].agg(_q, q=0.975).min()
        gain = 100 * (1 - np.exp(tc))
        right = result["pumping_recovery_share"]
        wrong = rows[["wrong_reasons_D", "wrong_reasons_C"]]
        if wrong.isna().any().any():
            raise ValueError(f"{setting} has worlds without both score 6 flags")
        fit = f"{worlds_path}:fits[{setting}]"
        entries = (
            ("DCMin", f"{dc.min():+.3f}", f"{D_OVER_C}, smallest cell median"),
            ("DCMax", f"{dc.max():+.3f}", f"{D_OVER_C}, largest cell median"),
            ("DCQHighMin", f"{high:+.3f}", f"{D_OVER_C}, smallest cell 97.5th percentile (twin_report._q)"),
            ("TCMin", f"{tc.min():+.3f}", f"{T_OVER_C}, smallest cell median"),
            ("TCMax", f"{tc.max():+.3f}", f"{T_OVER_C}, largest cell median"),
            ("TCGainMin", f"{gain.min():.1f}", f"{T_OVER_C}, smallest 100 * (1 - exp(cell median))"),
            ("TCGainMax", f"{gain.max():.1f}", f"{T_OVER_C}, largest 100 * (1 - exp(cell median))"),
            ("RightMin", f"{100 * right.min():.0f}", f"{PUMP_D} < {PUMP_C}, smallest cell percent"),
            ("RightMax", f"{100 * right.max():.0f}", f"{PUMP_D} < {PUMP_C}, largest cell percent"),
            ("RightMean", f"{100 * right.mean():.0f}", f"{PUMP_D} < {PUMP_C}, mean cell percent"),
            ("Pays", str(result["pays_count"]), f"{D_OVER_C}, cells that pay by twin_report.reading (a)"),
            ("WrongD", str(int(wrong["wrong_reasons_D"].sum())), "arm D score 6 count (twin_report.load)"),
            ("WrongC", str(int(wrong["wrong_reasons_C"].sum())), "arm C score 6 count (twin_report.load)"),
            ("Worlds", str(len(rows)), "worlds with both score 6 flags (twin_report.load)"),
        )
        lines.extend(rf"\newcommand{{\twin{name}{suffix}}}{{{value}}} % {fit}:{ref}"
                     for name, value, ref in entries)

    free_wins, cells_compared, nse_difference = compare_protocols(worlds)
    pairing = f"{worlds_path}:paired fits[free] and fits[pooled_l0.1_fixed3000], twin_report.reading (e)"
    lines.extend([
        rf"\newcommand{{\twinFreeBetterCells}}{{{free_wins}}} % {pairing}, lower median recovery_pumping_D",
        rf"\newcommand{{\twinCellsCompared}}{{{cells_compared}}} % {pairing}, cells compared",
        rf"\newcommand{{\twinNSEDiff}}{{{nse_difference:+.3f}}} % {pairing}, median cell difference in median nse_drought_D (free minus pooled)",
        rf"\newcommand{{\twinCells}}{{{len(EPS) * len(U)}}} % {worlds_path}:distinct (dials.eps, dials.u)",
        rf"\newcommand{{\twinWorldsPerCell}}{{{PLANNED_WORLDS}}} % {worlds_path}:checked distinct world IDs per cell and protocol",
    ])
    return "\n".join(lines) + "\n"


def draw_panel(ax, matrix, cmap, norm, fmt, show_y, pays=None):
    mesh = ax.pcolormesh(matrix, cmap=cmap, norm=norm, edgecolors="white", linewidth=0.65)
    for (row, col), value in np.ndenumerate(matrix):
        color = cmap(norm(value))
        luminance = np.dot(color[:3], (0.299, 0.587, 0.114))
        ax.text(col + 0.5, row + 0.5, format(value, fmt).replace("-", "−"),
                ha="center", va="center", color="white" if luminance < 0.5 else INK, fontsize=7.8)
    if pays is not None:
        for row, col in np.argwhere(pays):
            ax.add_patch(Rectangle((col + 0.035, row + 0.035), 0.93, 0.93, linewidth=1.65,
                                   edgecolor=INK, facecolor="none"))
    ax.set(ylim=(len(EPS), 0), xlim=(0, len(U)))
    ax.set_xticks(np.arange(len(U)) + 0.5, [f"{u:g}" for u in U])
    ax.set_yticks(np.arange(len(EPS)) + 0.5, [f"{e:g}" for e in EPS])
    ax.tick_params(length=0, pad=2.5, labelsize=7.5, labelcolor=INK, labelleft=show_y)
    for spine in ax.spines.values():
        spine.set_visible(False)
    return mesh


def draw_scale(fig, mesh, left, right, ticks, tick_format, label):
    cax = fig.add_axes([left, 0.085, right - left, 0.024])
    scale = fig.colorbar(mesh, cax=cax, orientation="horizontal", ticks=ticks, format=tick_format)
    # Matplotlib rasterizes long colour bars by default, even in a PDF.
    scale.solids.set_rasterized(False)
    scale.outline.set_visible(False)
    scale.ax.tick_params(length=2, width=0.5, labelsize=7, colors=INK, pad=2)
    scale.set_label(label, fontsize=7.4, color=INK, labelpad=2)


def draw_twin_map(out=OUT, *, tables_out=None):
    """Write the figure and optional TeX macros. Return the grids and pays counts."""
    worlds = load(["twin_map"])
    results, pays_cells = summarize_worlds(worlds)
    numbers = number_macros(worlds, results) if tables_out is not None else None
    limit = max(np.abs(result[key]).max() for result in results.values() for key in (D_OVER_C, T_OVER_C))
    diverging, sequential = matplotlib.colormaps["PuOr"], matplotlib.colormaps["cividis"]
    accuracy_norm, share_norm = Normalize(-limit, limit), Normalize(0, 1)

    fig, axes = plt.subplots(2, 3, figsize=(190 / 25.4, 116 / 25.4), facecolor="white")
    fig.subplots_adjust(left=0.145, right=0.97, bottom=0.226, top=0.924, hspace=0.30, wspace=0.16)
    heads = ("Accuracy of the graph (D / C)", "The oracle's ceiling (T / C)", "Right reasons")
    for ax, title in zip(axes[0], heads):
        ax.set_title(title, color=INK, fontsize=8, fontweight="bold", pad=6)
    for name, setting, row in zip(ROW_LABELS, PROTOCOLS, axes):
        result = results[setting]
        d_panel = draw_panel(row[0], result[D_OVER_C], diverging, accuracy_norm,
                             ".3f", show_y=True, pays=pays_cells[setting])
        draw_panel(row[1], result[T_OVER_C], diverging, accuracy_norm, ".3f", show_y=False)
        recovery_panel = draw_panel(row[2], result["pumping_recovery_share"], sequential, share_norm,
                                    ".0%", show_y=False)
        position = row[0].get_position()
        fig.text(0.084, (position.y0 + position.y1) / 2, name, rotation=90,
                 ha="center", va="center", color=INK, fontsize=8, fontweight="bold")
    fig.text(0.026, 0.575, "ε, share of the graph's pumping links that are false",
             rotation=90, ha="center", va="center", color=INK, fontsize=8)
    fig.text(0.564, 0.154, "u, share of the true pumping the graph misses",
             ha="center", va="center", color=INK, fontsize=8)
    left, middle, right = [ax.get_position() for ax in axes[-1]]
    draw_scale(fig, d_panel, left.x0, middle.x1, np.linspace(-limit, limit, 5),
               FormatStrFormatter("%.3f"), "Median log RMSE ratio")
    draw_scale(fig, recovery_panel, right.x0, right.x1, np.linspace(0, 1, 5),
               PercentFormatter(1, decimals=0), "Worlds with lower pumping error for D")

    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    with matplotlib.rc_context({"pdf.fonttype": 42}):
        fig.savefig(out / "twin_map.pdf", metadata={"Title": "The twin's knowledge-value map", "CreationDate": None})
        fig.savefig(out / "twin_map.png", dpi=200)
    plt.close(fig)
    if numbers is not None:
        tables_out = Path(tables_out)
        tables_out.mkdir(parents=True, exist_ok=True)
        (tables_out / "twin_numbers.tex").write_text(numbers, encoding="utf-8")
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, help="directory for the PDF, PNG and macros")
    parser.add_argument("--tables-out", type=Path, help="override the directory for twin_numbers.tex")
    args = parser.parse_args()
    for setting, result in draw_twin_map(args.out or OUT, tables_out=args.tables_out or args.out or TABLES_OUT).items():
        print(f"{setting}: {result['pays_count']} of {len(EPS) * len(U)} cells pay")


if __name__ == "__main__":
    main()
