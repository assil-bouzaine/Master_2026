"""Tuning budget of every tuned baseline: search space, trials, time, size of the selection.

    PFE_DATASET=v3 python -m src.analysis.tuning_report     # -> docs/tuning_budget_<v>.md

Equal trial counts are the starting rule (docs/analysis_plan.md §5), but a fair comparison
also states what each model was allowed to search and what it cost (third review,
docs/review_codex_2026-10-24.md §4): the search space, completed and failed trials, the
recorded trial time, the re-selection runs and the number of trainable parameters of the
selected network. Read from the Optuna studies (study.db), reselect.json and best.json of
the tuning folders; the networks are only built (random weights) to count parameters,
never trained. The v4 re-runs reuse these v3 selections (scripts/v4_from_v3.py). Trial
times come from different machines (laptop CPU, Camber and Colab GPUs: the step notes say
which), so they are not comparable across models.
"""
import argparse
import json
import warnings

import optuna
import pandas as pd

from src.config import DATASET, ROOT
from src.models.evaluate import DS, RESULTS

FOLDERS = [("LightGBM (no own climatology)", "lgbm_noclim_tuned", None),
           ("LightGBM (own climatology, sensitivity)", "lgbm_tuned", None),
           ("LSTM", "lstm_tuning", "lstm"), ("EA-LSTM", "ealstm_tuning", "ealstm"),
           ("Distance-graph ST-GNN", "stgnn_tuning", "stgnn"),
           ("Taccari-graph ST-GNN", "taccari_tuning", "taccari")]
OUT_MD = ROOT / "docs" / f"tuning_budget_{DATASET}.md"


def space_of(trials):
    def fmt(d):
        if isinstance(d, optuna.distributions.CategoricalDistribution):
            return "{" + ", ".join(map(str, d.choices)) + "}"
        lo, hi = d.low, d.high
        return f"[{lo:g}, {hi:g}]" + (" log" if getattr(d, "log", False) else "")
    dists = next(t.distributions for t in trials if t.distributions)
    return "; ".join(f"{k} {fmt(v)}" for k, v in dists.items())


def n_parameters(model, params):
    """Trainable parameters of the selected network (built with random weights only)."""
    import torch  # noqa: F401
    from src.models import lstm, stgnn
    from src.models.features import STATIC, build_panel
    P = build_panel()
    P = P[P["mu"].notna()]
    data = lstm.arrays(P)
    codes, X = data[0], data[2]
    if model in ("lstm", "ealstm"):
        net = lstm.ARCHS[model](X.shape[2], hidden=params["hidden"], dropout=params["dropout"],
                                n_static=len(STATIC))
    elif model == "stgnn":
        wells = pd.read_parquet(DS / "wells.parquet")
        net = stgnn.Net(X.shape[2], stgnn.distance_adjacency(codes, wells), params["hidden"],
                        params["dropout"])
    else:
        from src.models import taccari
        data = taccari.prepare(P, data)
        wells = pd.read_parquet(DS / "wells.parquet")
        ns = argparse.Namespace(hidden=params["hidden"], dropout=params["dropout"])
        net = taccari.build(data[0], wells, data[2].shape[2], ns)(data[2].shape[2])
    return sum(p.numel() for p in net.parameters() if p.requires_grad)


def main():
    warnings.filterwarnings("ignore")
    optuna.logging.set_verbosity(optuna.logging.WARNING)
    rows = []
    for label, folder, model in FOLDERS:
        d = RESULTS / folder
        if not (d / "study.db").exists():
            continue
        storage = f"sqlite:///{d / 'study.db'}"
        study = optuna.load_study(study_name=optuna.study.get_all_study_names(storage)[0],
                                  storage=storage)
        ts = study.trials
        state = lambda s: sum(t.state.name == s for t in ts)  # noqa: E731
        best = json.loads((d / "best.json").read_text())
        resel = json.loads((d / "reselect.json").read_text()) if (d / "reselect.json").exists() else {}
        rows.append({
            "model": label, "search space": space_of(ts),
            "trials complete": state("COMPLETE"), "failed": state("FAIL"),
            "pruned": state("PRUNED"),
            "trial time (h)": sum(t.duration.total_seconds() for t in ts if t.duration) / 3600,
            "re-selection runs": 2 * len(resel),
            "single-seed best (validation)": best.get("single_seed_best"),
            "selected trial": best.get("trial"),
            "selected 3-seed mean (validation)": best.get("validation_median_nse_3seed"),
            "selected": ", ".join(f"{k}={v:.3g}" if isinstance(v, float) else f"{k}={v}"
                                  for k, v in best["params"].items()),
            "trainable parameters": n_parameters(model, best["params"]) if model else None})
    t = pd.DataFrame(rows)
    md = ["# Tuning budget of the baselines (generated)\n",
          f"Generated by `python -m src.analysis.tuning_report` (dataset **{DATASET}**); do not "
          "edit by hand. Rule (`docs/analysis_plan.md` §5): Optuna TPE, seed 2026, 24 completed "
          "trials (failed trials are re-drawn and do not count), objective = median validation "
          "NSE over the core wells with one seed per trial; then the 3 best trials re-run with "
          "seeds 1 and 2 and the best 3-seed mean selected. Trial times come from different "
          "machines and are not comparable across models. LightGBM has no fixed parameter "
          "count (trees grow with early stopping).\n",
          t.to_markdown(index=False, floatfmt=".3f"), ""]
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    pd.set_option("display.width", 250, "display.max_columns", 20, "display.max_colwidth", 60)
    print(t.drop(columns=["search space"]).to_string(index=False))
    print("->", OUT_MD)


if __name__ == "__main__":
    main()
