REFERENCE_TAG = " [reference]"
HORIZONS = {4: "Four", 12: "Twelve"}
PHASE_METRICS = ("NSE drought", "skill drought", "NSE recovery", "skill recovery")
PHASE_HEADINGS = (r"\shortstack{NSE\\drought}", r"\shortstack{Skill\\drought}",
                  r"\shortstack{NSE\\recovery}", r"\shortstack{Skill\\recovery}")
TUNED_SINGLE_RUNS = tuple(f"{model}_tuned" for model, _ in baseline_report.REGIME_MODELS)
R2_REGIME = "R2 left-out monitored wells (5 folds)"
R3_REGIMES = ("R3 50 % of the training period", "R3 25 % of the training period")


def period_text(period):
    first, last = TEST_PERIODS[period]
    return f"{first} to {last or 'end of record'}"


def number_cell(value, decimals=2, *, signed=False):
    if math.isnan(value):
        return r"\textemdash{}"
    spec = f"+.{decimals}f" if signed else f".{decimals}f"
    return num(format(value, spec))


def table(kind, caption, columns, headings, rows):
    lines = [HEADER, r"\begin{table}[p]", r"\centering", r"\scriptsize",
             r"\setlength{\tabcolsep}{3pt}", rf"\caption{{{caption}}}",
             rf"\label{{tab:baselines-{kind}}}", rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
             r"\toprule", row(*headings), r"\midrule", *rows,
             r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def simulation_table(simulation, reference, periods):
    rows = [
        row(tex_escape(entry["model"].removesuffix(REFERENCE_TAG)),
            *(number_cell(entry[metric]) for metric in (*PHASE_METRICS, "KGE'' test")),
            number_cell(entry["wells"], 0))
        for _, entry in simulation.iterrows()
    ]
    caption = (f"Simulation baseline medians over the 33 core wells. {periods} "
               "Skill is relative to the training climatology. "
               f"The hydrology reference is {tex_escape(reference.removesuffix(REFERENCE_TAG))}.")
    headings = ("Model", *PHASE_HEADINGS, r"\shortstack{KGE$''$\\test}", "Wells")
    return table("simulation", caption, r"p{0.44\linewidth}rrrrrr", headings, rows)


def forecast_table(forecast, periods):
    rows = [
        row(number_cell(entry["h"], 0), tex_escape(entry["model"]),
            *(number_cell(entry[metric]) for metric in PHASE_METRICS),
            number_cell(entry["wells"], 0))
        for _, entry in forecast.iterrows()
    ]
    caption = (f"Forecast baseline medians over the 33 core wells. {periods} "
               "Skill is relative to anomaly persistence at the same horizon.")
    headings = (r"\shortstack{Horizon\\(weeks)}", "Model", *PHASE_HEADINGS, "Wells")
    return table("forecast", caption, r"rp{0.37\linewidth}rrrrr", headings, rows)


def load_drought_metric(path, metric):
    table_df = pd.read_csv(path)
    mask = (
        (table_df["task"] == "simulation")
        & (table_df["horizon"] == 0)
        & (table_df["split"] == "test_drought")
        & (table_df["variant"] == "all")
        & table_df["core"]
    )
    return table_df.loc[mask].set_index("code_bss")[metric]


def cluster_holm_table(metric, ref_path, model_series, well_clusters):
    """Compute exact cluster sign-flip p-values and Holm adjustment matching baseline_report."""
    reference = load_drought_metric(ref_path, metric)
    rows = []
    for run, series in model_series.items():
        paired = pd.concat([series.rename("a"), reference.rename("b")], axis=1).dropna()
        diff = paired["a"] - paired["b"]
        cells = well_clusters.loc[diff.index]
        groups = [group.to_numpy() for _, group in diff.groupby(cells.to_numpy())]
        p_cluster = sign_flip_p(groups, seed=2026) if (diff != 0).any() else 1.0
        rows.append({
            "run": run,
            "median_diff": float(diff.median()),
            "n_clusters": len(groups),
            "p_cluster": p_cluster,
        })
    frame = pd.DataFrame(rows).set_index("run")
    frame["p_holm"] = holm(frame["p_cluster"].to_numpy())
    return frame


def cluster_test_summaries():
    """Run the drought-phase cluster tests against the reference and all training-heads starts."""
    wells = pd.read_parquet(DS / "wells.parquet")
    well_clusters = clusters(wells)
    sim_runs = [
        run for run, _ in baseline_report.SIM
        if run != baseline_report.REFERENCE and (RESULTS / run / "metrics_per_well.csv").exists()
    ]
    nse_series = {run: load_drought_metric(RESULTS / run / "metrics_per_well.csv", "NSE")
                  for run in sim_runs}
    skill_series = {run: load_drought_metric(RESULTS / run / "metrics_per_well.csv", "skill")
                    for run in sim_runs}
    ref_path = RESULTS / baseline_report.REFERENCE / "metrics_per_well.csv"
    sig_nse = cluster_holm_table("NSE", ref_path, nse_series, well_clusters)
    sig_skill = cluster_holm_table("skill", ref_path, skill_series, well_clusters)

    starts = start_runs(f"{PASTAS_BASE}_trainobs")
    per_start = [cluster_holm_table("NSE", run_dir / "metrics_per_well.csv", nse_series, well_clusters)
                 for run_dir in starts]
    robust = pd.concat(per_start).groupby(level=0).agg(
        p_holm_max=("p_holm", "max"),
        pass_count=("p_holm", lambda p: int((p < 0.05).sum())),
    )
    return sig_nse, sig_skill, robust


def number_macros(simulation, forecast, reference, spread, regimes, sig_nse, sig_skill, robust):
    """Record the report row and column beside each command."""
    lines = [NUMBERS_HEADER]
    forecast_labels = dict(baseline_report.FC)
    chronos = [label for run, label in baseline_report.FC if run.startswith("chronos2")]
    for horizon, suffix in HORIZONS.items():
        models = forecast.loc[forecast["h"] == horizon].set_index("model")
        best = models.loc[chronos, "NSE drought"].idxmax()
        source = f"{SOURCE}, forecast, {horizon} weeks"
        lines.append(rf"\newcommand{{\baselineChronos{suffix}Variant}}{{{tex_escape(best)}}}"
                     f" % {source}, model with maximum drought NSE")
        for name, model in (("Chronos", best), ("LightGBM", forecast_labels["lgbm_fc"]),
                            ("AnomalyPersistence", forecast_labels["naive_anomaly_persist"])):
            value = number_cell(models.at[model, "NSE drought"])
            lines.append(rf"\newcommand{{\baseline{name}{suffix}DroughtNSE}}{{{value}}}"
                         f" % {source}, {model}, NSE drought")
        skill_value = number_cell(models.at[best, "skill drought"])
        lines.append(rf"\newcommand{{\baselineChronos{suffix}DroughtSkill}}{{{skill_value}}}"
                     f" % {source}, {best}, skill drought")

    simulation_labels = dict(baseline_report.SIM)
    models = simulation.set_index("model")
    for name, model in (("Pastas", reference), ("LSTM", simulation_labels["lstm_tuned"]),
                        ("DistanceSTGNN", simulation_labels["stgnn_tuned"]),
                        ("Ensemble", simulation_labels["ensemble_sim"])):
        for metric, suffix in (("NSE drought", "NSE"), ("skill drought", "Skill")):
            value = number_cell(models.at[model, metric])
            lines.append(rf"\newcommand{{\baseline{name}Drought{suffix}}}{{{value}}}"
                         f" % {SOURCE}, simulation, {model}, {metric}")

    clim_label = simulation_labels["naive_climatology"]
    lines.append(rf"\newcommand{{\baselineClimatologyDroughtNSE}}"
                 rf"{{{number_cell(models.at[clim_label, 'NSE drought'])}}}"
                 f" % {SOURCE}, simulation, {clim_label}, NSE drought")
    ealstm_label = simulation_labels["ealstm_tuned"]
    for metric, suffix in (("NSE drought", "NSE"), ("skill drought", "Skill")):
        value = number_cell(models.at[ealstm_label, metric])
        lines.append(rf"\newcommand{{\baselineEALSTMDrought{suffix}}}{{{value}}}"
                     f" % {SOURCE}, simulation, {ealstm_label}, {metric}")

    spread_src = "src/analysis/baseline_report.py:reference_spread(), training heads only"
    trainobs = spread.loc[spread["construction"] == "training heads only"].iloc[0]
    start_cols = [col for col in spread.columns if col.startswith("start ")]
    start_values = [float(trainobs[col]) for col in start_cols]
    lines.append(rf"\newcommand{{\baselinePastasStarts}}{{{number_cell(len(start_cols), 0)}}}"
                 f" % {spread_src}, count of starts")
    lines.append(rf"\newcommand{{\baselinePastasStartMinDroughtNSE}}"
                 rf"{{{number_cell(min(start_values))}}}"
                 f" % {spread_src}, min drought NSE across starts")
    lines.append(rf"\newcommand{{\baselinePastasStartMaxDroughtNSE}}"
                 rf"{{{number_cell(max(start_values))}}}"
                 f" % {spread_src}, max drought NSE across starts")
    lines.append(rf"\newcommand{{\baselinePastasWellRangeMedian}}"
                 rf"{{{number_cell(float(trainobs['per-well range, median']))}}}"
                 f" % {spread_src}, per-well range, median")

    sig_src = "src/analysis/baseline_report.py:significance_table()"
    lines.append(rf"\newcommand{{\baselineClusterCount}}"
                 rf"{{{number_cell(int(sig_nse.at['ensemble_sim', 'n_clusters']), 0)}}}"
                 f" % {sig_src}, test_drought, NSE, n_clusters")
    lines.append(rf"\newcommand{{\baselineEnsembleDiffDroughtNSE}}"
                 rf"{{{number_cell(sig_nse.at['ensemble_sim', 'median_diff'], signed=True)}}}"
                 f" % {sig_src}, ensemble_sim, test_drought, NSE, median_diff")
    lines.append(rf"\newcommand{{\baselineEnsemblePHolmDroughtNSE}}"
                 rf"{{{number_cell(sig_nse.at['ensemble_sim', 'p_holm'], 3)}}}"
                 f" % {sig_src}, ensemble_sim, test_drought, NSE, p_holm")
    lines.append(rf"\newcommand{{\baselineEnsemblePHolmDroughtSkill}}"
                 rf"{{{number_cell(sig_skill.at['ensemble_sim', 'p_holm'], 3)}}}"
                 f" % {sig_src}, ensemble_sim, test_drought, skill, p_holm")
    lines.append(rf"\newcommand{{\baselineDistanceSTGNNPHolmDroughtSkill}}"
                 rf"{{{number_cell(sig_skill.at['stgnn_tuned', 'p_holm'], 3)}}}"
                 f" % {sig_src}, stgnn_tuned, test_drought, skill, p_holm")

    rob_src = "src/analysis/baseline_report.py:reference_robustness()"
    lines.append(rf"\newcommand{{\baselineEnsembleStartsPass}}"
                 rf"{{{number_cell(int(robust.at['ensemble_sim', 'pass_count']), 0)}}}"
                 f" % {rob_src}, ensemble_sim, starts with p_holm < 0.05")
    lines.append(rf"\newcommand{{\baselineEnsembleStartsMaxPHolm}}"
                 rf"{{{number_cell(float(robust.at['ensemble_sim', 'p_holm_max']), 3)}}}"
                 f" % {rob_src}, ensemble_sim, p_holm max")
    single_passes = [int(robust.at[run, "pass_count"]) for run in TUNED_SINGLE_RUNS]
    lines.append(rf"\newcommand{{\baselineSingleStartsPassMin}}"
                 rf"{{{number_cell(min(single_passes), 0)}}}"
                 f" % {rob_src}, five tuned single models, min starts with p_holm < 0.05")
    lines.append(rf"\newcommand{{\baselineSingleStartsPassMax}}"
                 rf"{{{number_cell(max(single_passes), 0)}}}"
                 f" % {rob_src}, five tuned single models, max starts with p_holm < 0.05")

    reg_src = "src/analysis/baseline_report.py:regimes_table()"
    r2 = regimes.loc[regimes["regime"] == R2_REGIME]
    r3 = regimes.loc[regimes["regime"].isin(R3_REGIMES)]
    for tag, subset, desc in (("Two", r2, "R2"), ("Three", r3, "R3 50%/25%")):
        for metric, suffix in (("NSE drought", "NSE"), ("skill drought", "Skill")):
            lines.append(rf"\newcommand{{\baselineRegime{tag}MinDrought{suffix}}}"
                         rf"{{{number_cell(float(subset[metric].min()))}}}"
                         f" % {reg_src}, {desc}, min {metric}")
            lines.append(rf"\newcommand{{\baselineRegime{tag}MaxDrought{suffix}}}"
                         rf"{{{number_cell(float(subset[metric].max()))}}}"
                         f" % {reg_src}, {desc}, max {metric}")
    return "\n".join(lines) + "\n"


def generate(out=OUT):
    """Prepare the three fragments before writing any of them."""
    if DATASET != "v4":
        raise ValueError("The paper baseline tables require PFE_DATASET=v4")
    main_table = baseline_report.main_table()
    simulation = main_table.loc[(main_table["task"] == "simulation") & (main_table["h"] == 0)]
    forecast = main_table.loc[(main_table["task"] == "forecast") & main_table["h"].isin(HORIZONS)]
    reference = simulation.loc[simulation["model"].str.endswith(REFERENCE_TAG), "model"].item()
    spread = baseline_report.reference_spread()
    regimes = baseline_report.regimes_table()
    sig_nse, sig_skill, robust = cluster_test_summaries()
    periods = (f"Drought covers {period_text('test_drought')}. "
               f"Recovery covers {period_text('test_recovery')}.")
    documents = {
        "baselines_simulation.tex": simulation_table(simulation, reference, periods),
        "baselines_forecast.tex": forecast_table(forecast, periods),
        "baselines_numbers.tex": number_macros(
            simulation, forecast, reference, spread, regimes, sig_nse, sig_skill, robust
        ),
    }
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, content in documents.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {out / name}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT, help="output folder (default: paper/tables)")
    args = parser.parse_args(argv)
    generate(args.out)


if __name__ == "__main__":
    main()
