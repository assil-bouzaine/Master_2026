"""Write the paper's simulation and forecast tables from the v4 baseline report.

This supports the endpoints and test periods in analysis plan sections 1 and 2.
Use the report's core-well medians and model labels so the tables and the
commands used in the text agree. Choose the best Chronos-2 variant at each
horizon before rounding its score. No model is fitted for this build.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/baseline_tables.py [--out DIR]
"""
