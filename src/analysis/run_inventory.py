"""Which runs can be executed again, and which are predictions only (Codex review of 2026-10-26, §8).

    PFE_DATASET=v4 python -m src.analysis.run_inventory
    -> results/<v>/run_inventory.csv and docs/run_inventory_<v>.md

A stored prediction table can be rescored, but only a run kept with its fitted model can be run
again on new weeks (the check on weeks observed after the freeze, analysis plan §11), explained
or probed with an intervention. Per run folder, and per fold of a leave-wells-out run:
  replayable        neural: manifest.json, schema.json and a checkpoint seed_<k>.pt for every seed
                    that has predictions; LightGBM: manifest.json and model_seed_<k>.txt for every
                    seed; Pastas: params.csv (tests/test_replay.py rebuilds the models from it)
  recomputable      nothing fitted: the naive baselines (from the dataset) and the ensemble (from
                    its members' stored predictions)
  predictions only  stored predictions without the fitted model: runs from before checkpoints were
                    saved (2026-10-24), or whose checkpoints stayed on Kaggle or Colab
Nothing is completed after the fact: a run listed "predictions only" is rerun under a new run
identity if a later check needs its model.
"""
import re

import pandas as pd

from src.config import DATASET, ROOT
from src.models.evaluate import RESULTS

NEURAL = ("lstm", "ealstm", "stgnn", "taccari", "chronos")


def kind_of(name):
    if name.startswith("naive_") or name.startswith("ensemble"):
        return "recomputable"
    if name.startswith("pastas"):
        return "pastas"
    if name.startswith("lgbm"):
        return "lightgbm"
    if name.startswith(NEURAL):
        return "neural"
    return "other"


def seeds(folder, pattern):
    return {int(m.group(1)) for f in folder.iterdir() if (m := re.fullmatch(pattern, f.name))}


def status(folder, kind):
    """(status, seeds with predictions, seeds with a fitted model) of one folder."""
    has = {f.name for f in folder.iterdir()}
    if kind == "recomputable":
        return "recomputable", None, None
    if kind == "pastas":
        return ("replayable" if "params.csv" in has else "predictions only"), None, None
    if kind == "lightgbm":
        fitted = seeds(folder, r"model_seed_(\d+)\.txt")
        ok = "manifest.json" in has and fitted
        return ("replayable" if ok else "predictions only"), None, len(fitted)
    pred = seeds(folder, r"seed_(\d+)\.parquet")
    fitted = seeds(folder, r"seed_(\d+)\.pt")
    ok = {"manifest.json", "schema.json"} <= has and pred and pred <= fitted
    return ("replayable" if ok else "predictions only"), len(pred), len(fitted)


def inventory():
    rows = []
    for run in sorted(p for p in RESULTS.iterdir() if p.is_dir() and not p.name.startswith("_")):
        if not (run / "predictions.parquet").exists():
            continue
        kind = kind_of(run.name)
        folds = sorted(p for p in run.iterdir() if p.is_dir() and p.name.startswith("fold_"))
        parts = [status(f, kind) for f in folds] if folds else [status(run, kind)]
        states = {s for s, _, _ in parts}
        state = states.pop() if len(states) == 1 else "partly replayable"
        n_pred = sum(p for _, p, _ in parts if p is not None) if parts[0][1] is not None else None
        n_fit = sum(f for _, _, f in parts if f is not None) if parts[0][2] is not None else None
        rows.append({"run": run.name, "kind": kind, "folds": len(folds) or None, "status": state,
                     "seed_predictions": n_pred, "fitted_models": n_fit})
    return pd.DataFrame(rows)


def main():
    t = inventory()
    t.to_csv(RESULTS / "run_inventory.csv", index=False)
    counts = t["status"].value_counts().to_dict()
    lines = [f"# Run inventory, dataset {DATASET}", "",
             f"Generated by `src/analysis/run_inventory.py` from `results/{DATASET}/` "
             "(Codex review of 2026-10-26, §8). A run is **replayable** when its fitted model is kept "
             "(neural checkpoints with their manifest and input schema, LightGBM boosters with their "
             "manifest, Pastas parameters), **recomputable** when nothing is fitted (naive baselines, "
             "the ensemble), and **predictions only** otherwise: its tables can be rescored, but it "
             "cannot be run on new weeks or probed. Nothing is completed after the fact; a model "
             "needed later is rerun under a new run identity.", "",
             "Counts: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + ".", "",
             "| Run | Kind | Folds | Status | Seed predictions | Fitted models |",
             "|---|---|---|---|---|---|"]
    fmt = lambda v: "" if pd.isna(v) else str(int(v))  # noqa: E731
    for r in t.itertuples():
        lines.append(f"| `{r.run}` | {r.kind} | {fmt(r.folds)} | {r.status} | {fmt(r.seed_predictions)} "
                     f"| {fmt(r.fitted_models)} |")
    out = ROOT / "docs" / f"run_inventory_{DATASET}.md"
    out.write_text("\n".join(lines) + "\n")
    print(t.to_string(index=False))
    print(f"-> {out.relative_to(ROOT)}; {counts}")


if __name__ == "__main__":
    main()
