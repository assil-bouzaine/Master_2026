"""Write the paper's data tables and number commands from the saved v4 dataset.

This supports analysis plan sections 2 to 4: periods, wells and grouped folds.
Read dataset_v4 metadata and weekly tables, the KG facts summary, the RPG
edition filenames, and the model's saved gauge and test-period definitions.
Write data_sources.tex, data_periods.tex and data_numbers.tex. Numbers are
never typed by hand. Provider names come from the step notes and CLAUDE.md.
No current time or output path enters the files, so rebuilds are identical.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/data_tables.py [--out DIR]
"""
import argparse
import json
from pathlib import Path
import re
import sys
import unicodedata

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
if not __package__:
    sys.path.insert(0, str(ROOT))

from paper.tools.kg_tables import num, row, tex_escape
from src.config import TEST_PERIODS
from src.models.features import NEAR_CANDIDATES, RIVERS

DATASET = ROOT / "data" / "processed" / "dataset_v4"
OUT = ROOT / "paper" / "tables"
COMMAND = "PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/data_tables.py"
SOURCES = {name: DATASET / filename for name, filename in (
    ("meta", "meta.json"), ("splits", "splits.json"), ("wells", "wells.parquet"),
    ("heads", "heads_weekly.parquet"), ("forcing", "forcing_weekly.parquet"),
    ("points", "pumping_points.parquet"), ("pumping", "pumping_weekly.parquet"),
    ("gauges", "gauges.parquet"), ("rivers", "rivers_weekly.parquet"))}
SOURCES |= {"kg": ROOT / "data/processed/kg/lulcw_kg_v4_summary.json",
            "config": ROOT / "src/config.py", "features": ROOT / "src/models/features.py"}
PROVIDER_FILES = tuple(ROOT / path for path in (
    "docs/notes/step04_piezometers.md", "docs/notes/step05_rpg.md", "docs/notes/step06a_bnpe.md",
    "docs/notes/step06b_bdlisa.md", "docs/notes/step08_dataset.md", "CLAUDE.md"))
# Names only, copied from the allowed notes; the report gives their file and line.
PROVIDERS = {
    "Groundwater heads": "Hub'Eau piezometers",             # step04_piezometers.md:1
    "Weather": "Météo-France; SAFRAN / SIM2",                # CLAUDE.md, Step 8
    "Abstraction": "Hub'Eau; BNPE",                          # step06a_bnpe.md:1,9
    "Rivers": "Hub'Eau hydrometrie",                         # CLAUDE.md, Step 8
    "Hydrogeology": "BD LISA",                               # step06b_bdlisa.md:1
    "Land use": "IGN; RPG",                                 # step05_rpg.md:9
}
PERIOD_LABELS = {"warmup": "Warm-up", "train": "Train", "validation": "Validation", "test": "Test",
                 "drought": "Test: drought", "recovery": "Test: recovery"}


def source(name, key):
    return f"{SOURCES[name].relative_to(ROOT).as_posix()}:{key}"


def read_sources():
    """Read only saved data and count actual RPG editions, without opening their geometry."""
    data = {name: (pd.read_parquet(path) if path.suffix == ".parquet"
                   else json.loads(path.read_text(encoding="utf-8")))
            for name, path in SOURCES.items() if path.suffix in (".json", ".parquet")}
    data["rpg"] = sorted((int(match[1]), path)
                         for path in (ROOT / "data/interim").glob("rpg_dept_*.parquet")
                         if (match := re.fullmatch(r"rpg_dept_(\d{4})\.parquet", path.name)))
    if not data["rpg"]:
        raise ValueError("No data/interim/rpg_dept_<year>.parquet editions found")
    return data


def header(data):
    """Name concrete source files, including every RPG edition, without a wall-clock time."""
    paths = [*SOURCES.values(), *PROVIDER_FILES, *(path for _, path in data["rpg"])]
    names = ", ".join(path.relative_to(ROOT).as_posix() for path in paths)
    return f"% Generated by {COMMAND}; sources: {names}\n"


def date_text(value):
    return pd.Timestamp(value).date().isoformat()


def week_range(frame, value=None):
    """A series' period covers observations, not empty dates or station metadata."""
    weeks = frame.loc[frame[value].notna(), "week"] if value else frame["week"]
    if weeks.empty:
        raise ValueError("Cannot describe a series without observed weeks")
    return date_text(weeks.min()), date_text(weeks.max())


def summarize(data):
    """Keep full-file coverage separate from the modelling window and annual declarations."""
    wells, points, pumping = (data[name] for name in ("wells", "points", "pumping"))
    used = sorted(set(RIVERS.values()) | set(NEAR_CANDIDATES))
    if missing := set(used) - set(data["gauges"]["code_station"]):
        raise ValueError("Model gauges missing from gauges.parquet: " + ", ".join(sorted(missing)))
    rivers = data["rivers"].loc[data["rivers"]["code_station"].isin(used)]
    if set(rivers.loc[rivers["q_m3s"].notna(), "code_station"]) != set(used):
        raise ValueError("A model gauge has no observed discharge in rivers_weekly.parquet")
    declared = pumping.loc[pumping["imputed"].eq(False), "week"]
    if declared.empty:
        raise ValueError("No non-imputed pumping rows from which to find the first declared year")
    groups = wells.groupby("group", dropna=False)["code_bss"].nunique().to_dict()
    return {
        "wells": int(wells["code_bss"].nunique()),
        "core_wells": int(wells.loc[wells["core"].eq(True), "code_bss"].nunique()),
        "groups": sorted(groups.items(), key=lambda item: (-item[1], item[0])),
        "weather_cells": int(data["forcing"]["cell_id"].nunique()),
        "weather_variables": [name for name in data["forcing"].columns if name not in ("cell_id", "week")],
        "groundwater_points": int(points.loc[points["source"] == "groundwater", "code_ouvrage"].nunique()),
        "surface_points": int(points.loc[points["source"] == "surface", "code_ouvrage"].nunique()),
        "uses": sorted(pumping["usage"].dropna().unique()),
        "first_declared_year": int(declared.dt.year.min()),
        "last_declared_year": data["meta"]["last_bnpe_year"],
        "imputed_rows": int(pumping["imputed"].eq(True).sum()), "pumping_rows": len(pumping),
        "imputed_percent": f"{100 * pumping['imputed'].eq(True).mean():.2f}",
        "gauges": int(data["gauges"]["code_station"].nunique()), "used_gauges": used,
        "polygons": data["kg"]["polygons"], "units": data["kg"]["instances_by_class"]["HydrogeologicalUnit"],
        "rpg_years": [year for year, _ in data["rpg"]],
        "head_dates": week_range(data["heads"], "head"), "weather_dates": week_range(data["forcing"]),
        "pumping_dates": week_range(pumping), "river_dates": week_range(rivers, "q_m3s"),
    }


def periods(data):
    """Count Sunday labels inside saved date boundaries; observations can have gaps."""
    splits, meta = data["splits"], data["meta"]
    bounds = {"warmup": (splits["forcing_start"],
                         date_text(pd.Timestamp(splits["model_start"]) - pd.Timedelta(days=1)))}
    refs = {"warmup": (source("splits", "forcing_start"), source("splits", "model_start minus one day"))}
    for name in ("train", "validation", "test"):
        bounds[name] = tuple(splits[name])
        refs[name] = tuple(source("splits", f"{name}[{index}]") for index in (0, 1))
    for name in ("drought", "recovery"):
        first, last = TEST_PERIODS["test_" + name]
        bounds[name] = (max(first, splits["test"][0]),
                        min(last or meta["last_week"], splits["test"][1], meta["last_week"]))
        refs[name] = (source("config", f"TEST_PERIODS.test_{name}[0]; clipped to splits.json:test"),
                      source("config", f"TEST_PERIODS.test_{name}[1]; capped by splits.json:test[1] and "
                             "meta.json:last_week"))
    return {name: {"start": date_text(first), "end": date_text(last),
                   "weeks": len(pd.date_range(first, last, freq=splits["week_rule"])),
                   "start_source": refs[name][0], "end_source": refs[name][1]}
            for name, (first, last) in bounds.items()}


def sources_table(data, summary):
    """Describe data families and clearly state the denominator of the imputation share."""
    s = summary
    head_groups = "; ".join(f"{tex_escape(name)} {num(count)}" for name, count in s["groups"])
    variables = ", ".join(rf"\texttt{{{tex_escape(name)}}}" for name in s["weather_variables"])
    gauges = ", ".join(rf"\texttt{{{tex_escape(code)}}}" for code in s["used_gauges"])
    ranges = {key: " to ".join(s[key + "_dates"]) for key in ("head", "weather", "pumping", "river")}
    entries = (
        ("Groundwater heads", f"{num(s['wells'])} piezometers ({num(s['core_wells'])} core); " + head_groups,
         "Weekly", ranges["head"]),
        ("Weather", f"{num(s['weather_cells'])} cells; variables: " + variables, "Weekly", ranges["weather"]),
        ("Abstraction", f"{num(s['groundwater_points'])} groundwater points and {num(s['surface_points'])} "
         "surface points; uses: " + ", ".join(tex_escape(use) for use in s["uses"]) + "; "
         f"weeks without a usable declaration (before {num(s['first_declared_year'])}, after "
         f"{num(s['last_declared_year'])}, and corrected or missing declarations in between) are filled "
         "and marked as imputed",
         "Annual declarations spread to weeks",
         f"Declarations: {num(s['first_declared_year'])}--{num(s['last_declared_year'])}; "
         "weekly series: " + ranges["pumping"]),
        ("Rivers", f"{num(len(s['used_gauges']))} model gauges out of {num(s['gauges'])} in the file; "
         "discharge from " + gauges, "Weekly", ranges["river"]),
        ("Hydrogeology", f"{num(s['polygons'])} polygons and {num(s['units'])} hydrogeological units "
         "in the facts graph", "Static", "—"),
        ("Land use", f"{num(len(s['rpg_years']))} RPG editions", "Annual",
         ", ".join(num(year) for year in s["rpg_years"])),
    )
    lines = [header(data).rstrip(), r"\begin{table}[p]", r"\centering", r"\scriptsize",
             r"\setlength{\tabcolsep}{2pt}",
             r"\caption{Data used in the study. Series periods show the first and last available weeks "
             r"in the saved files; the modelling periods are reported separately.}",
             r"\label{tab:data-sources}",
             r"\begin{tabular}{@{}p{0.12\linewidth}p{0.16\linewidth}p{0.40\linewidth}p{0.10\linewidth}p{0.16\linewidth}@{}}",
             r"\toprule", row("Data", "Provider and product", "What this study uses", "Time step", "Period"), r"\midrule"]
    for index, (family, uses, step, period) in enumerate(entries):
        if index:
            lines.append(r"\addlinespace")
        lines.append(row(family, tex_escape(PROVIDERS[family]), uses, step, period))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def periods_table(data, windows):
    lines = [header(data).rstrip(), r"\begin{table}[p]", r"\centering", r"\small",
             r"\setlength{\tabcolsep}{2pt}",
             r"\caption{Modelling periods and spatial folds. Counts are Sunday-labelled calendar weeks "
             r"within the saved date boundaries, not counts of observations. Drought and recovery partition "
             r"the test period. Warm-up ends the day before the model starts.}",
             r"\label{tab:periods}",
             r"\begin{tabular}{@{}p{0.19\linewidth}p{0.18\linewidth}p{0.18\linewidth}p{0.14\linewidth}p{0.25\linewidth}@{}}",
             r"\toprule",
             row("Period or design", "Start", "End", "Weeks / folds", "Spatial grouping"), r"\midrule"]
    for name, window in windows.items():
        lines.append(row(PERIOD_LABELS[name], window["start"], window["end"], num(window["weeks"]), ""))
    lines += [r"\midrule", row("Leave-wells-out", "—", "—",
              num(data["splits"]["leave_wells_out"]["n_folds"]) + " folds",
              "Single-linkage; wells $< " + num(data["meta"]["config"]["fold_link_m"]) + "$ m apart"),
              r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def group_suffix(name):
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii")
    return "".join(word.capitalize() for word in re.findall("[A-Za-z]+", ascii_name))


def number_macros(data, summary, windows):
    """Use distinct data-prefixed commands so they can be loaded beside the KG commands."""
    s = summary
    rpg_source = "data/interim/rpg_dept_<year>.parquet (matching edition filenames)"
    entries = [
        ("nDataWells", s["wells"], source("wells", "count(distinct code_bss)")),
        ("nDataCoreWells", s["core_wells"], source("wells", "core=true: count(distinct code_bss)")),
        ("nDataWeatherCells", s["weather_cells"], source("forcing", "count(distinct cell_id)")),
        ("nDataGroundwaterPoints", s["groundwater_points"], source("points", "source=groundwater: count(distinct code_ouvrage)")),
        ("nDataSurfacePoints", s["surface_points"], source("points", "source=surface: count(distinct code_ouvrage)")),
        ("nDataGauges", s["gauges"], source("gauges", "count(distinct code_station)")),
        ("nDataGaugesUsed", len(s["used_gauges"]), source("features", "RIVERS.values union NEAR_CANDIDATES")),
        ("nDataRpgEditions", len(s["rpg_years"]), rpg_source),
        ("nDataRpgFirstYear", min(s["rpg_years"]), rpg_source + ": minimum year"),
        ("nDataRpgLastYear", max(s["rpg_years"]), rpg_source + ": maximum year"),
        ("nDataFolds", data["splits"]["leave_wells_out"]["n_folds"], source("splits", "leave_wells_out.n_folds")),
        ("nDataFoldLinkMetres", data["meta"]["config"]["fold_link_m"], source("meta", "config.fold_link_m")),
        ("nDataPolygons", s["polygons"], source("kg", "polygons")),
        ("nDataUnits", s["units"], source("kg", "instances_by_class.HydrogeologicalUnit")),
        ("nDataFirstDeclaredYear", s["first_declared_year"], source("pumping", "imputed=false: min(week.year)")),
        ("nDataLastDeclaredYear", s["last_declared_year"], source("meta", "last_bnpe_year")),
        ("nDataImputedRows", s["imputed_rows"], source("pumping", "count(imputed=true), all rows")),
        ("nDataPumpingRows", s["pumping_rows"], source("pumping", "row count, all years and uses")),
        ("nDataImputedPercent", s["imputed_percent"], source("pumping", "100 * mean(imputed=true), all rows, rounded to two decimals")),
    ]
    for group, count in s["groups"]:
        entries.append(("nDataGroup" + group_suffix(group) + "Wells", count,
                        source("wells", f"group={group}: count(distinct code_bss)")))
    text_entries = [("dataLastWeek", data["meta"]["last_week"], source("meta", "last_week"))]
    for name, window in windows.items():
        suffix = name.capitalize()
        refs = window["start_source"] + "; " + window["end_source"]
        entries.append(("nData" + suffix + "Weeks", window["weeks"], source("splits", "week_rule") + "; " + refs))
        text_entries += [("data" + suffix + boundary, window[boundary.lower()], window[boundary.lower() + "_source"])
                         for boundary in ("Start", "End")]
    for name, key, file in (("Heads", "head", "heads"), ("Weather", "weather", "forcing"),
                            ("Pumping", "pumping", "pumping"), ("Rivers", "river", "rivers")):
        condition = " (non-null head)" if file == "heads" else " (model gauge union, non-null q_m3s)" if file == "rivers" else ""
        text_entries += [("data" + name + boundary + "Week", value, source(file, operation + "(week)" + condition))
                         for boundary, value, operation in zip(("First", "Last"), s[key + "_dates"], ("min", "max"))]
    names = [entry[0] for entry in entries + text_entries]
    if len(set(names)) != len(names) or any(re.fullmatch(r"(?:nData|data)[A-Za-z]+", name) is None for name in names):
        raise ValueError("Data command names must be unique, data-prefixed and letters only")
    lines = [header(data).rstrip()]
    lines += [rf"\newcommand{{\{name}}}{{{num(value)}}} % {ref}" for name, value, ref in entries]
    lines += [rf"\newcommand{{\{name}}}{{{value}}} % {ref}" for name, value, ref in text_entries]
    return "\n".join(lines) + "\n"


def generate(out=OUT):
    data = read_sources()
    summary, windows = summarize(data), periods(data)
    documents = {"data_sources.tex": sources_table(data, summary), "data_periods.tex": periods_table(data, windows),
                 "data_numbers.tex": number_macros(data, summary, windows)}
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, content in documents.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {out / name}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT, help="output folder (default: paper/tables)")
    args = parser.parse_args(argv)
    generate(args.out)


if __name__ == "__main__":
    main()
