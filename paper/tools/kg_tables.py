"""Write the paper's KG tables and number commands from the saved graph outputs.

This supports the graph inventory in analysis plan section 14, items 14 and 15.
Read the v4 facts summary, rules summary, release record, inventory JSON, and
the exported arm C and D edges and nodes. Write kg_instances.tex,
kg_coverage.tex and kg_numbers.tex. Numbers are never typed by hand: they come
from those files. The release timestamp makes repeated builds identical.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/kg_tables.py [--out DIR]
"""
import argparse
from datetime import datetime
import json
from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
KG = ROOT / "data" / "processed" / "kg"
OUT = ROOT / "paper" / "tables"
COMMAND = "PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python paper/tools/kg_tables.py"
SOURCES = {
    "facts": KG / "lulcw_kg_v4_summary.json",
    "rules": KG / "lulcw_kg_v4_rules_summary.json",
    "release": KG / "lulcw_kg_v4_release.json",
    "inventory": KG / "inventory_v4_main.json",
    "C": KG / "export_v4_main" / "edges_C.parquet",
    "D": KG / "export_v4_main" / "edges_D.parquet",
    "nodes": KG / "export_v4_main" / "nodes.parquet",
}
GROUPS = (
    ("Hydrogeology", ("HydrogeologicalUnit", "HydrogeologicalUnitGroup", "MultilayerAquiferSystem",
                      "GroundwaterBody", "AlluvialAquifer", "KarstAquifer", "ConfiningUnit",
                      "ElementaryPolygon", "StackLayer")),
    ("Monitoring", ("Piezometer", "MonitoringStation", "ObservationSeries")),
    ("Abstraction", ("AbstractionFacility", "Intake", "AnnualAbstractionRecord", "UnitAttribution",
                     "SurfaceWaterIntake", "CanalIntakeGroup")),
    ("Surface water", ("Watercourse", "RiverReach", "ReachPiece", "RiverSection", "RiverGauge",
                       "GaugePool", "GaugeZoneRelation", "SurfaceWaterBody", "CanalReach",
                       "ReachSearchZone")),
    ("Documents", ("Document", "DocumentPassage", "ExchangeStatement")),
    ("Land use and demand", ("CropCode", "CropClass", "CropAreaObservation", "CropDemandEstimate",
                             "CropDemandZone")),
    ("Weather and recharge", ("WeatherCell", "PolygonCellIntersection", "OutcropSearchZone")),
    ("Provenance and rules", ("SourceRecord", "DataRelease", "DerivationRule", "Procedure",
                             "RuleExecution", "RuleEvaluation", "ConstraintDecision", "ExportPolicy",
                             "Ontology")),
    ("Geometry, time and vocabularies", ("Geometry", "Feature", "Instant", "ProperInterval",
                                        "ConceptScheme")),
)
RELATIONS = ("pumping", "pumping_unattributed", "recharge", "recharge_unitwide", "river", "canal",
             "well_link")


def read_sources():
    """Read saved files only; generating the paper never rebuilds the graph."""
    return {name: (pd.read_parquet(path) if path.suffix == ".parquet"
                   else json.loads(path.read_text(encoding="utf-8")))
            for name, path in SOURCES.items()}


def tex_escape(value):
    """Keep source labels readable without treating their punctuation as LaTeX."""
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
                    "^": r"\textasciicircum{}"}
    return "".join(replacements.get(char, char) for char in value)


def num(value):
    return rf"\num{{{value}}}"


def row(*cells):
    return " & ".join(cells) + r" \\"


def header(released, source_names):
    """Record source paths and release time, never the current time or output path."""
    paths = ", ".join(SOURCES[name].relative_to(ROOT).as_posix() for name in source_names)
    return f"% Generated by {COMMAND}; sources: {paths}; released: {released}\n"


def grouped_classes(counts):
    """Keep all classes, but refuse a missing expected class rather than imply zero."""
    listed = {name for _, names in GROUPS for name in names}
    missing = listed - counts.keys()
    if missing:
        raise ValueError("Listed facts classes missing from instances_by_class: " + ", ".join(sorted(missing)))
    groups = list(GROUPS)
    other = counts.keys() - listed
    if other:
        print("WARNING: facts classes placed in Other: " + ", ".join(sorted(other)), file=sys.stderr)
        groups.append(("Other", tuple(other)))
    # Alphabetical ties make the output independent of the JSON key order.
    return [(theme, sorted(names, key=lambda name: (-counts[name], name))) for theme, names in groups]


def well_codes(nodes):
    """Use well nodes only: other node types have empty core flags."""
    wells = nodes.loc[nodes["type"] == "well"]
    return set(wells["code"]), set(wells.loc[wells["core"].eq(True), "code"])


def coverage(edges, core):
    """Count direct, directed edges and distinct source nodes within each relation."""
    out = {}
    for relation, group in edges.groupby("relation", sort=False):
        out[relation] = {
            "wells": int(group["dst"].nunique()),
            "core_wells": int(group.loc[group["dst"].isin(core), "dst"].nunique()),
            "edges": len(group),
            "eligible_edges": int(group["eligible"].eq(True).sum()),
            "constrained_edges": int(group["constrained"].eq(True).sum()),
            "distinct_sources": len(group[["src_type", "src"]].drop_duplicates()),
        }
    return out


def inventory_diagnostics(counts, totals):
    """Explain the inventory's per-well source sum and expose every different total."""
    messages = ["Inventory totals.*.sources sums per-well source counts (src/kg/inventory.py:totals); "
                "it counts source-well edges, while the paper also reports distinct sources."]
    for relation in RELATIONS:
        if relation not in totals:
            messages.append(f"NOTE: inventory totals has no {relation}; no inventory cross-check is available.")
            continue
        actual = counts.get(relation, dict.fromkeys(
            ("wells", "core_wells", "edges", "eligible_edges", "constrained_edges", "distinct_sources"), 0))
        for key in ("wells", "core_wells", "sources", "eligible_edges", "constrained_edges"):
            if key not in totals[relation]:
                messages.append(f"NOTE: inventory totals.{relation}.{key} is absent; no cross-check is available.")
                continue
            saved = totals[relation][key]
            edge_key = "distinct_sources" if key == "sources" else key
            if saved != actual[edge_key]:
                extra = (f"; edge rows={actual['edges']} (the inventory sums sources per well)"
                         if key == "sources" else "")
                messages.append(f"WARNING: inventory totals.{relation}.{key}={saved}; "
                                f"edges_D.parquet {edge_key}={actual[edge_key]}{extra}.")
            if key == "sources" and saved != actual["edges"]:
                messages.append(f"WARNING: inventory totals.{relation}.sources={saved}; "
                                f"edges_D.parquet edges={actual['edges']}; the per-well source sum differs too.")
    return messages


def instances_table(facts, rules, released):
    """Show class memberships rather than add overlapping classes into an entity total."""
    groups = grouped_classes(facts["instances_by_class"])
    lines = [header(released, ("facts", "rules", "release")).rstrip(),
             r"\begin{table}[p]", r"\centering", r"\scriptsize",
             r"\caption{Instances in the facts graph, grouped by theme. The final rows give the triples "
             r"of the facts graph and the triples derived by the rules.}", r"\label{tab:kg-instances}",
             r"\begin{tabular}{@{}llr@{}}", r"\toprule", row("Theme", "Class or graph", "Count"), r"\midrule"]
    for index, (theme, names) in enumerate(groups):
        if index:
            lines.append(r"\addlinespace")
        for position, name in enumerate(names):
            lines.append(row(rf"\textbf{{{tex_escape(theme)}}}" if position == 0 else "",
                             rf"\texttt{{{tex_escape(name)}}}", num(facts["instances_by_class"][name])))
    lines += [r"\midrule", row("", "Facts graph triples", num(facts["triples"])),
              row("", "Triples derived by the rules", num(rules["rule_triples"])), r"\bottomrule",
              r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def coverage_table(counts_c, counts_d, released):
    """Keep eligible and actually constrained edges separate, including zero counts."""
    unexpected = counts_d.keys() - set(RELATIONS)
    if unexpected:
        raise ValueError("Arm D relations missing from the table order: " + ", ".join(sorted(unexpected)))
    lines = [header(released, ("C", "D", "nodes", "inventory", "release")).rstrip(),
             r"\begin{table}[p]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
             r"\caption{Direct coverage of wells in arm C (distance rules) and arm D (knowledge graph). "
             r"Parentheses count core wells. Sources are distinct within each relation; edges are directed "
             r"source-to-well connections. An em dash marks a relation absent from arm C.}",
             r"\label{tab:arm-coverage}", r"\begin{tabular}{@{}lrrrrrrrr@{}}", r"\toprule",
             row("Relation", r"\shortstack{D wells\\(core)}", r"\shortstack{D\\edges}",
                 r"\shortstack{D eligible\\edges}", r"\shortstack{D constrained\\edges}",
                 r"\shortstack{D distinct\\sources}", r"\shortstack{C wells\\(core)}",
                 r"\shortstack{C\\edges}", r"\shortstack{C distinct\\sources}"), r"\midrule"]
    for relation in RELATIONS:
        d = counts_d.get(relation, dict.fromkeys(
            ("wells", "core_wells", "edges", "eligible_edges", "constrained_edges", "distinct_sources"), 0))
        cells = [rf"\texttt{{{tex_escape(relation)}}}", f"{num(d['wells'])} ({num(d['core_wells'])})",
                 *(num(d[key]) for key in ("edges", "eligible_edges", "constrained_edges", "distinct_sources"))]
        c = counts_c.get(relation)
        cells += ([f"{num(c['wells'])} ({num(c['core_wells'])})", num(c["edges"]), num(c["distinct_sources"])]
                  if c is not None else ["—", "—", "—"])
        lines.append(row(*cells))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def number_macros(facts, rules, nodes, released):
    """Keep each command next to its exact source key so prose can reuse the same counts."""
    classes = facts["instances_by_class"]
    derived = rules["derived"]
    mechanisms = derived["influences_by_mechanism"]
    eligibility = derived["influences_by_eligibility"]
    pairs = derived["influence_facility_well_pairs_by_policy"]["main"]
    wells, core = well_codes(nodes)
    entries = [
        ("nKgFactTriples", facts["triples"], "facts", "triples"),
        ("nKgRuleTriples", rules["rule_triples"], "rules", "rule_triples"),
        ("nKgClasses", len(classes), "facts", "instances_by_class (number of keys)"),
        ("nKgPiezometers", classes["Piezometer"], "facts", "instances_by_class.Piezometer"),
        ("nKgFacilities", classes["AbstractionFacility"], "facts", "instances_by_class.AbstractionFacility"),
        ("nKgAnnualRecords", facts["annual_records"], "facts", "annual_records"),
        ("nKgPolygons", facts["polygons"], "facts", "polygons"),
        ("nKgUnits", classes["HydrogeologicalUnit"], "facts", "instances_by_class.HydrogeologicalUnit"),
        ("nInflPumping", mechanisms["PumpingDrawdown"], "rules", "derived.influences_by_mechanism.PumpingDrawdown"),
        ("nInflRecharge", mechanisms["DiffuseRecharge"], "rules", "derived.influences_by_mechanism.DiffuseRecharge"),
        ("nInflRiver", mechanisms["RiverExchange"], "rules", "derived.influences_by_mechanism.RiverExchange"),
        ("nInflCanal", mechanisms["CanalReturnFlow"], "rules", "derived.influences_by_mechanism.CanalReturnFlow"),
        ("nInflEligible", eligibility["EligibleConstraint"], "rules",
         "derived.influences_by_eligibility.EligibleConstraint"),
        ("nInflIneligible", eligibility["IneligibleConstraint"], "rules",
         "derived.influences_by_eligibility.IneligibleConstraint"),
        ("nDPumpPairs", pairs["pairs"], "rules", "derived.influence_facility_well_pairs_by_policy.main.pairs"),
        ("nDPumpFacilities", pairs["facilities"], "rules",
         "derived.influence_facility_well_pairs_by_policy.main.facilities"),
        ("nDPumpWells", pairs["wells"], "rules", "derived.influence_facility_well_pairs_by_policy.main.wells"),
        ("nWellLinksMain", derived["well_links_selected_by_policy"]["main"], "rules",
         "derived.well_links_selected_by_policy.main"),
        ("nWells", len(wells), "nodes", "type=well: count(distinct code)"),
        ("nCoreWells", len(core), "nodes", "type=well, core=true: count(distinct code)"),
    ]
    lines = [header(released, ("facts", "rules", "nodes", "release")).rstrip()]
    for name, value, source, key in entries:
        path = SOURCES[source].relative_to(ROOT).as_posix()
        lines.append(rf"\newcommand{{\{name}}}{{{num(value)}}} % {path}:{key}")
    date = datetime.fromisoformat(released).date().isoformat()
    path = SOURCES["release"].relative_to(ROOT).as_posix()
    lines.append(rf"\newcommand{{\kgRelease}}{{{date}}} % {path}:released (date part)")
    return "\n".join(lines) + "\n"


def generate(out=OUT):
    """Prepare every file before writing, so missing classes cannot leave half a build."""
    data = read_sources()
    released = data["release"]["released"]
    _, core = well_codes(data["nodes"])
    counts_c, counts_d = (coverage(data[arm], core) for arm in ("C", "D"))
    documents = {
        "kg_instances.tex": instances_table(data["facts"], data["rules"], released),
        "kg_coverage.tex": coverage_table(counts_c, counts_d, released),
        "kg_numbers.tex": number_macros(data["facts"], data["rules"], data["nodes"], released),
    }
    for message in inventory_diagnostics(counts_d, data["inventory"]["totals"]):
        print(message, file=sys.stderr)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, content in documents.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {out / name}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT, help="output folder (default: paper/tables)")
    args = parser.parse_args(argv)
    generate(args.out)


if __name__ == "__main__":
    main()
