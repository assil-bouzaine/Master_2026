"""Compare the black box on knowledge-graph and distance edges (analysis plan §14 items 23–24).

    PFE_DATASET=v4 python -m src.analysis.blackbox_report

Read saved scores to compare edge choices for the same model on the same machine.
Show the machine diagnostic and the hybrid and baseline scores for context.
"""
import pandas as pd

from src.analysis import ladder_report as ladder, stats
from src.config import DATASET, ROOT
from src.models.evaluate import DS, RESULTS

RUNS = {
    "taccari_D": "Tuned Taccari-style ST-GNN on arm D's knowledge-graph edges (L4, five seeds)",
    "taccari_tuned_ctl": "Same tuned ST-GNN on its usual distance edges (same L4 session, five seeds)",
    "taccari_tuned": "Tuned Taccari-style ST-GNN on distance edges (October T4 baseline of record)",
    "stgnn_tuned": "Tuned distance-graph ST-GNN baseline",
    "lstm_tuned": "Tuned LSTM baseline",
    ladder.REFERENCE: "Pastas hydrology reference (best start by the frozen rule)",
    "p4_B2_D_r1": "Phase 4 hybrid on arm D's knowledge-graph edges (early stopping, reconstruction 1)",
    "p4_B2_C_r1": "Phase 4 hybrid on arm C's distance edges (early stopping, reconstruction 1)",
}
CONTRASTS = (
    ("taccari_D", "taccari_tuned_ctl", "pre-specified", "Edge choice in the same L4 session"),
    ("taccari_tuned_ctl", "taccari_tuned", "diagnostic", "Machine effect (L4 vs October T4)"),
    ("taccari_D", "p4_B2_D_r1", "descriptive", "Black box vs hybrid on arm D's edges"),
    ("taccari_tuned_ctl", "p4_B2_C_r1", "descriptive", "Black box vs hybrid on distance edges"),
)
SCORE_METRICS = ("NSE val", "NSE drought", "skill drought", "RMSE drought")
CONTRAST_METRICS = {
    "median log(RMSE a / RMSE b)": "Median log(RMSE a / RMSE b)",
    "interval": "95% cluster-bootstrap interval",
    "share of wells a better": "Share of wells a better",
    "p_cluster": "Cluster sign-flip p",
    "support mismatch": "Support mismatch (wells)",
}
OUTPUT = ROOT / "docs" / f"results_blackbox_{DATASET}.md"


def _table(headings, rows):
    return "\n".join("| " + " | ".join(row) + " |" for row in (headings, ["---"] * len(headings), *rows))


def _contrasts(metrics, wells, contrasts):
    rows, support = [], []
    for a, b, reading, purpose in contrasts:
        ma, mb = metrics[a], metrics[b]
        prefix = f"Exact support for `{a}` vs `{b}`"
        status = "scored"
        if ma is None or mb is None:
            status = "pending"
            if reading == "pre-specified":
                support.append(f"{prefix} is pending.")
        elif reading == "pre-specified":
            try:
                check = stats.paired(ma, mb, wells, metric="RMSE", strict=True)
            except ValueError as error:
                status = "support check failed"
                support.append(f"{prefix} failed. {error}")
            else:
                support.append(f"{prefix} passed. Both runs scored the same well-weeks at "
                               f"{check['n_wells']} paired core wells.")
        values = ladder.contrast(ma, mb, wells) if status == "scored" else {}
        rows.append([f"`{a}`", f"`{b}`", reading, purpose, status,
                     *(ladder.fmt(values.get(key), nd=4) for key in CONTRAST_METRICS)])
    return rows, support


def render(wells, *, runs=RUNS, contrasts=CONTRASTS, results=RESULTS):
    """Read the declared runs' scores and render the two tables."""
    metrics = {}
    scores = []
    for run, description in runs.items():
        path = results / run / "metrics_per_well.csv"
        table = pd.read_csv(path) if path.is_file() else None
        metrics[run] = table
        values = ladder.medians(table) if table is not None else {}
        scores.append([f"`{run}`", description, "pending" if table is None else "scored",
                       *(ladder.fmt(values.get(key)) for key in SCORE_METRICS)])
    comparisons, support = _contrasts(metrics, wells, contrasts)
    sections = [
        "# Black box on the knowledge graph's edges (generated)",
        f"Generated by `python -m src.analysis.blackbox_report` (dataset **{DATASET}**). Do not edit by hand.",
        "The **pre-specified** contrast asks whether the knowledge graph's edges improve the tuned "
        "Taccari-style ST-GNN in the same L4 session. It follows the analysis plan's wording "
        "“pre-specified comparisons on a previously examined benchmark”. The **diagnostic** "
        "contrast measures the machine effect for the same model and distance edges. The "
        "**descriptive** comparisons with the hybrid pair runs by edge rule across different "
        "model classes and machines. The distance rules use individual pumping facilities in arm C "
        "and grouped pumping fields in the black box. "
        "[Gate 3 point 21](gate3_decisions.md#5-ontology-scope-and-reporting), "
        "[analysis plan §12](analysis_plan.md#12-wording-of-claims-added-in-v2) and "
        "[§14 items 23–24](analysis_plan.md#14-amendments-before-the-tag-2026-10-24-to-2026-11-10).",
        "## Scores",
        "Median simulation scores over the core wells. Skill is measured against climatology. "
        "RMSE is in metres. Pending runs are awaiting saved scores.",
        _table(["Run", "Model", "Status", "Validation NSE", "Drought NSE", "Drought skill", "Drought RMSE"], scores),
        "## Contrasts",
        "The effect is the median drought log(RMSE a / RMSE b) across paired core wells. "
        "Negative values favour run a. Support mismatch counts paired wells scored on different weeks. "
        "For older scores without support digests, the diagnostic and descriptive rows compare week counts.",
        _table(["Run a", "Run b", "Reading", "Comparison", "Status", *CONTRAST_METRICS.values()], comparisons),
        *support,
    ]
    return "\n\n".join(sections) + "\n"


def main(output=OUTPUT, *, runs=RUNS, contrasts=CONTRASTS, results=RESULTS):
    wells = pd.read_parquet(DS / "wells.parquet")
    output.write_text(render(wells, runs=runs, contrasts=contrasts, results=results), encoding="utf-8")
    print(f"-> {output}")


if __name__ == "__main__":
    main()
