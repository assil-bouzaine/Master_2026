"""Checks of the response-function superposition (src/models/response.py).

    python -m tests.test_response

1. Kernels: non-negative, sum to 1, bounded time scales.
2. Convolution: equals an explicit loop over lags, and is causal (a change at week t0 never
   changes an output before t0).
3. Exact decomposition: constant + contributions = output.
4. Signs through the whole path (analysis plan §10, hard monotonicity): raising rain or canal
   water never lowers a head, raising pumping or ETP never raises one, for random parameters,
   impulses and sustained changes, with the model's own preprocessing.
5. Sharing: in "shared" mode the wells of a group have the same response parameters and no
   trainable deviation; in "pooled" mode the penalty is 0 at delta = 0 and grows with it.
6. Recovery on a small synthetic set: heads generated by known responses are fitted, and the
   recovered contributions follow the true ones (a smoke test of the training loop, seconds).
"""
import numpy as np
import torch

from src.models import response as R


def toy_inputs(N=6, T=160, K=40, seed=0):
    rng = np.random.default_rng(seed)
    X = {"rain": rng.gamma(0.4, 3.0, (N, T + K - 1)), "ETP": 1.5 + rng.random((N, T + K - 1)),
         "PE": rng.normal(0.3, 2.0, (N, T + K - 1)), "pump_gw": rng.gamma(2.0, 0.3, (N, T + K - 1)),
         "canal": np.repeat(rng.random((1, T + K - 1)), N, 0)}
    X["pump_pp"] = np.repeat(X["pump_gw"].min(1, keepdims=True), T + K - 1, 1)
    X["pump_sp"] = X["pump_gw"] - X["pump_pp"]
    return {k: v.astype(np.float32) for k, v in X.items()}


def model(N=6, K=40, mode="free", seed=0, init_sd=1.0, pumping="sum"):
    g = torch.Generator().manual_seed(seed)
    return R.ResponseModel(np.arange(N) % 2, 2, mode, kernel_weeks=K, amax=20.0, init_sd=init_sd,
                           generator=g, pumping=pumping)


def tt(X):
    return {k: torch.from_numpy(v) for k, v in X.items()}


def test_kernels():
    net = model()
    gain, a, n, f = net.parameters_physical()
    w = net.kernels(a, n)
    assert (w >= 0).all() and torch.allclose(w.sum(-1), torch.ones_like(w.sum(-1)), atol=1e-5)
    assert (a > R.A_MIN).all() and (a < 20.0).all() and (n > R.N_MIN).all() and (n < R.N_MAX).all()
    assert (f > 0).all() and (f < R.F_MAX).all()
    assert (gain[:, 0] >= 0).all() and (gain[:, 1] <= 0).all() and (gain[:, 2] >= 0).all()


def test_convolution_and_causality():
    N, T, K = 6, 160, 40
    X, net = toy_inputs(N, T, K), model(N, K)
    with torch.no_grad():
        c = net.contributions(tt(X)).numpy()
        gain, a, n, f = (t.numpy() for t in net.parameters_physical())
        w = net.kernels(*[torch.from_numpy(v) for v in (a, n)]).numpy()
    S = np.stack([X["rain"] - f[:, None] * X["ETP"], X["pump_gw"], X["canal"]], 1)
    i, r, t = 3, 1, 57                              # one well, pumping, one week
    want = gain[i, r] * sum(w[i, r, j] * S[i, r, t + K - 1 - j] for j in range(K))
    assert abs(c[i, r, t] - want) < 1e-4, (c[i, r, t], want)
    X2 = {k: v.copy() for k, v in X.items()}
    t0 = 90
    X2["pump_gw"][:, t0 + K - 1] += 5.0             # padded index of week t0
    with torch.no_grad():
        d = (net(tt(X2)) - net(tt(X))).numpy()
    assert np.abs(d[:, :t0]).max() == 0.0, "a later change moved an earlier head"
    assert (d[:, t0:] <= 1e-6).all() and d[:, t0:].min() < 0


def test_decomposition():
    X, net = toy_inputs(), model()
    with torch.no_grad():
        out, c = net(tt(X)), net.contributions(tt(X))
        assert torch.allclose(out, net.d[:, None] + c.sum(1), atol=1e-5)


def test_signs():
    N, T, K = 6, 160, 40
    rng = np.random.default_rng(1)
    for seed in range(5):
        for recharge in ("linear", "pe"):
            net = model(N, K, seed=seed, init_sd=2.0)
            net.recharge = recharge
            X = toy_inputs(N, T, K, seed)
            with torch.no_grad():
                base = net(tt(X)).numpy()
            for name, sign in (("rain", 1), ("ETP", -1), ("PE", 1), ("pump_gw", -1), ("canal", 1)):
                used = not (recharge == "pe" and name in ("rain", "ETP")) and \
                    not (recharge == "linear" and name == "PE")
                for kind in ("impulse", "sustained"):
                    X2 = {k: v.copy() for k, v in X.items()}
                    t0 = int(rng.integers(0, T + K - 2))
                    sl = slice(t0, t0 + 1) if kind == "impulse" else slice(t0, None)
                    X2[name][:, sl] += float(rng.uniform(0.1, 3.0))
                    with torch.no_grad():
                        d = net(tt(X2)).numpy() - base
                    if not used:
                        assert np.abs(d).max() == 0.0, (name, recharge)
                    else:
                        assert (sign * d >= -1e-5).all(), (name, kind, recharge, (sign * d).min())
                        assert (sign * d).max() > 0, (name, kind, recharge)


def test_split_pumping():
    """--pumping split: two pumping stresses, both with non-positive gains, each acting alone;
    and panel_arrays' permanent part is constant within a calendar year, the two parts add up."""
    N, T, K = 6, 160, 40
    net, X = model(N, K, pumping="split", init_sd=1.5), toy_inputs(N, T, K)
    assert net.names == ("recharge", "pumping_permanent", "pumping_seasonal", "canal")
    gain = net.parameters_physical()[0]
    assert (gain[:, 1] <= 0).all() and (gain[:, 2] <= 0).all()
    with torch.no_grad():
        base = net(tt(X)).numpy()
        assert torch.allclose(net(tt(X)), net.d[:, None] + net.contributions(tt(X)).sum(1), atol=1e-5)
    for name in ("pump_pp", "pump_sp"):
        X2 = {k: v.copy() for k, v in X.items()}
        X2[name][:, 70:] += 1.0
        with torch.no_grad():
            d = net(tt(X2)).numpy() - base
        assert (d <= 1e-5).all() and d.min() < 0, name
    X2 = {k: v.copy() for k, v in X.items()}
    X2["pump_gw"] += 5.0                                  # the sum is not an input in this mode
    with torch.no_grad():
        assert np.abs(net(tt(X2)).numpy() - base).max() == 0.0
    import pandas as pd
    weeks = pd.date_range("2010-01-03", periods=120, freq="W")
    rng = np.random.default_rng(0)
    P = pd.DataFrame({"code_bss": np.repeat(["a", "b"], 120), "week": np.tile(weeks, 2),
                      "split": "train", "core": True, "group": "g", "head": 1.0, "mu": 1.0, "sd": 1.0,
                      "rain": 1.0, "ETP": 1.0, "PE": 0.0, "canal": 0.0,
                      "pump_gw": rng.gamma(2.0, 50.0, 240)})
    d = R.panel_arrays(P, kernel_weeks=10)
    pp, sp, tot = (d["X"][k][:, 9:] for k in ("pump_pp", "pump_sp", "pump_gw"))
    for y in (2010, 2011):
        m = weeks.year == y
        assert np.ptp(pp[:, m], axis=1).max() < 1e-6, "the permanent part moves within a year"
        winter = m & np.isin(weeks.month, R.WINTER_MONTHS)
        assert np.allclose(pp[:, m][:, 0], tot[:, winter].mean(1), atol=1e-5)
    assert (sp >= 0).all() and np.allclose(sp, np.clip(tot - pp, 0, None), atol=1e-5)


def test_gain_units():
    """--gain-units sd: the same raw parameters give contributions scaled by each well's sd, the
    signs still hold, and a shared model then gives every well of a group the same response in
    units of its own sd."""
    N, K = 6, 40
    scale = np.array([0.05, 0.1, 0.5, 1.0, 2.0, 5.0], dtype=np.float32)
    g = torch.Generator().manual_seed(4)
    a = R.ResponseModel(np.arange(N) % 2, 2, "shared", kernel_weeks=K, amax=20.0, init_sd=1.0, generator=g)
    g = torch.Generator().manual_seed(4)
    b = R.ResponseModel(np.arange(N) % 2, 2, "shared", kernel_weeks=K, amax=20.0, init_sd=1.0, generator=g,
                        gain_scale=scale)
    X = toy_inputs(N, 120, K)
    with torch.no_grad():
        ca, cb = a.contributions(tt(X)).numpy(), b.contributions(tt(X)).numpy()
        gain = b.parameters_physical()[0].numpy()
    assert np.allclose(cb, ca * scale[:, None, None], rtol=1e-5, atol=1e-7)
    assert (gain[:, 0] >= 0).all() and (gain[:, 1] <= 0).all()
    rel = gain / scale[:, None]
    for grp in (0, 1):
        m = np.arange(N) % 2 == grp
        assert np.allclose(rel[m], rel[m][:1], rtol=1e-5)


def test_sharing():
    net = model(mode="shared")
    assert not net.delta.requires_grad and net.delta.abs().sum().item() == 0.0
    gain, a, n, f = net.parameters_physical()
    for g in (0, 1):
        m = net.group_of == g
        assert torch.allclose(a[m], a[m][:1].expand_as(a[m])) and torch.allclose(gain[m], gain[m][:1].expand_as(gain[m]))
    net = model(mode="pooled")
    assert net.penalty().item() == 0.0
    with torch.no_grad():
        net.delta += 0.5
    assert abs(net.penalty().item() - 0.25) < 1e-6
    free = model(mode="free")
    assert free.penalty().item() > 0


def test_recovery():
    N, T, K = 6, 260, 40
    X = toy_inputs(N, T, K, seed=3)
    truth = model(N, K, seed=11, init_sd=0.7)
    with torch.no_grad():
        truth.d += torch.linspace(-0.3, 0.3, N)
        y, c_true = truth(tt(X)).numpy(), truth.contributions(tt(X)).numpy()
    rng = np.random.default_rng(5)
    head = y + rng.normal(0, 0.003, y.shape)     # small against the weakest well's signal
    split = np.array([["train"] * 180 + ["validation"] * 80] * N, dtype=object)
    mu = np.repeat(head[:, :180].mean(1, keepdims=True), T, 1)
    sd = np.repeat(head[:, :180].std(1, keepdims=True), T, 1)
    data = {"X": X, "head": head, "mu": mu, "sd": sd, "split": split,
            "core": np.ones((N, T), bool), "groups": ["a", "b"], "group_of": np.arange(N) % 2,
            "codes": [f"w{i}" for i in range(N)], "weeks": np.arange(T)}
    net, best, step = R.train_seed(0, data, "free", steps=1500, lr=0.05, patience=40, eval_every=20,
                                   kernel_weeks=K, amax=20.0)
    assert best > 0.85, best
    with torch.no_grad():
        c = net.contributions(tt(X)).numpy()
    for r, name in enumerate(R.STRESSES):
        cc = [np.corrcoef(c[i, r], c_true[i, r])[0, 1] for i in range(N)]
        assert np.median(cc) > 0.9, (name, cc)


