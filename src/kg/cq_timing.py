"""Time every competency-question query on the persisted graph store (v5 plan R2.4, Gate R2: "Oxigraph
queries execute in < 1 s").

The calls timed are exactly those of the CQ test suites' data checks (tests/test_cq.py: test_data,
test_data_forcing, test_data_recharge, test_data_rivers, test_data_cq15, and any later test_data_*
function with the same signatures), run on the read-only store of src.kg.store instead of the
in-memory store the tests build for themselves. So the parameters are the real ones the CQ contracts
are tested with (every core well, every unit, every year the tests ask for), and the checks still
assert their answers: a timing run is also a run of the data tests. Each call of src.kg.cq.ask (and of
`one`, which uses it) is timed by name of its query file; the oracle queries the tests send directly
to the store are not CQ queries and are not timed.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v5 python -m src.kg.cq_timing     # -> docs/cq_timing_v5.md

Writes one row per query file of tests/cq/ (calls, median, 95th percentile, maximum, rows returned)
and exits with status 1 when a query's slowest call reaches the limit (1 s). A query file no data
check calls is listed as "not called" (CQ10 and CQ16 have no real data yet: fixtures only).
"""
import inspect
import statistics
import sys
import time
from collections import defaultdict
from datetime import datetime, timezone

from src.config import DATASET, ROOT
from src.kg import cq
from src.kg.store import persisted_store, read_record

LIMIT_S = 1.0
OUT = ROOT / "docs" / f"cq_timing_{DATASET}.md"


def timed_ask(record, original):
    def ask(store, name, **params):
        t = time.perf_counter()
        rows = original(store, name, **params)
        record[name].append((time.perf_counter() - t, len(rows)))
        return rows
    return ask


TOP_LEVEL = {"store", "facts_file"}


def data_checks(test_cq):
    """The top-level data checks of tests/test_cq.py, in file order: the test_data* functions that take
    only the store (and the facts file), as its main() calls them; the others (test_data_pumps,
    test_data_landuse) are called from test_data with arguments it computes."""
    fns = [(n, f) for n, f in vars(test_cq).items()
           if n.startswith("test_data") and inspect.isfunction(f) and f.__module__ == test_cq.__name__
           and set(inspect.signature(f).parameters) <= TOP_LEVEL]
    return sorted(fns, key=lambda nf: nf[1].__code__.co_firstlineno)


def run(store, record):
    import tests.test_cq as t
    facts = cq.KG / f"lulcw_kg_{DATASET}.ttl"
    original = cq.ask
    cq.ask = t.ask = timed_ask(record, original)          # `one` calls cq.ask through its module globals
    try:
        for name, f in data_checks(t):
            args = [store if p == "store" else facts for p in inspect.signature(f).parameters]
            t0 = time.time()
            f(*args)
            print(f"  {name}: {time.time() - t0:.0f} s", flush=True)
    finally:
        cq.ask = t.ask = original


def table(record):
    lines = ["| Query | Calls | Median (s) | 95th pct (s) | Max (s) | Rows (max) | Under 1 s |",
             "|---|---:|---:|---:|---:|---:|---|"]
    slow = []
    for f in sorted((cq.CQ).glob("*.rq")):
        name = f.stem
        calls = record.get(name, [])
        if not calls:
            lines.append(f"| `{name}` | 0 | | | | | not called |")
            continue
        ts = sorted(c[0] for c in calls)
        p95 = ts[min(len(ts) - 1, round(0.95 * (len(ts) - 1)))]
        ok = ts[-1] < LIMIT_S
        if not ok:
            slow.append(name)
        lines.append(f"| `{name}` | {len(ts)} | {statistics.median(ts):.3f} | {p95:.3f} | {ts[-1]:.3f} | "
                     f"{max(c[1] for c in calls)} | {'yes' if ok else '**no**'} |")
    return lines, slow


def main():
    t0 = time.time()
    store = persisted_store()
    rec = read_record()
    print(f"store of release {rec['release']} ({rec['triples']:,} triples) opened in {time.time() - t0:.1f} s")
    record = defaultdict(list)
    run(store, record)
    lines, slow = table(record)
    n_calls = sum(len(v) for v in record.values())
    head = [f"# CQ query times on the persisted store ({DATASET})", "",
            f"Generated by `python -m src.kg.cq_timing` on "
            f"{datetime.now(timezone.utc).isoformat(timespec='seconds')} (laptop, 4 cores). Store "
            f"`data/processed/kg/store_{DATASET}/` (pyoxigraph {rec['pyoxigraph']}, read-only), loaded from "
            f"the graph release of {rec['release']} ({rec['triples']:,} triples). The calls are those of the "
            f"CQ test suites' data checks (`tests/test_cq.py`), with their real parameters: {n_calls:,} "
            f"calls of {len(record)} query files; the checks' answers were asserted in the same run. "
            f"Gate R2 asks every query to execute in under {LIMIT_S:g} s: "
            + ("**every called query passes**." if not slow else f"**{len(slow)} do not**: "
               + ", ".join(f"`{s}`" for s in slow) + "."), ""]
    OUT.write_text("\n".join(head + lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}; {n_calls} calls; slow: {slow or 'none'}")
    return 1 if slow else 0


if __name__ == "__main__":
    sys.exit(main())
