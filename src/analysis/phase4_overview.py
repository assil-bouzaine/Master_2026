"""Show the absolute scores of the Phase 4 runs beside the reference models.

Read the per-well scores already on disk and use the launcher dry run to find
the full schedule. This is a descriptive view of the development benchmark
(analysis plan §11 and §14 items 18 and 20).

    PFE_DATASET=v4 python -m src.analysis.phase4_overview
"""
import os
import sys
from dataclasses import dataclass

import pandas as pd

from scripts.p4_queue import DEFAULT_STEPS, build_plan
from src.analysis.ladder_report import fmt, medians, per_well
from src.config import DATASET, RESULTS_DIR, ROOT

BLOCKS = tuple(step.removeprefix("p4_") for step in DEFAULT_STEPS.split())
REFERENCES = (
    "lstm_tuned", "stgnn_tuned", "taccari_tuned", "taccari_D",
    "pastas_seasonal_canal_trainobs_beststart", "resp_pooled_l001",
    "resp_pooled_l01_conv", "naive_climatology",
)
REGIMES = {"lwo": "_lwo", "f25": "_f25", "f50": "_f50", "refit": "_refit"}
METRICS = ("NSE val", "NSE drought", "skill drought", "RMSE drought", "KGE drought")
SCORE_HEADERS = ("Core wells scored", "NSE validation", "NSE drought", "Skill drought",
                 "RMSE drought (m)", "KGE″ drought", "Status")


@dataclass(frozen=True)
class Run:
    name: str
    block: str
    arm: str
    reconstruction: int
    suffix: str


def phase4_plan():
    """Read the declared schedule even if the shell has local Phase 4 overrides."""
    env = {key: value for key, value in os.environ.items() if not key.startswith("P4_")}
    env["PY"] = sys.executable
    return build_plan(DEFAULT_STEPS, env=env)


def report_runs(plan):
    """Keep one row per output folder in the order of the dry-run commands."""
    fits = {task.id: task for task in plan.tasks if task.kind == "fit"}
    runs = []
    for task in plan.tasks:
        if task.fold is not None:
            continue
        # Read the fit settings from a fold, but take scores from the assembly folder.
        argv = fits[task.deps[0]].argv if task.kind == "assembly" else task.argv
        arm = argv[argv.index("--arm") + 1]
        if arm == "baseline":
            arm = argv[argv.index("--statics") + 1]
        reconstruction = int(argv[argv.index("--pumping-reconstruction") + 1])
        _, block, _ = task.run.split("_", 2)
        suffix = REGIMES.get(task.run.rsplit("_", 1)[-1], "")
        runs.append(Run(task.run, block, arm, reconstruction, suffix))
    return runs


def read_scores(path):
    """Read the saved core-well medians and count wells with a drought RMSE."""
    if not path.is_file():
        return None
    metrics = pd.read_csv(path)
    scores = medians(metrics)
    scores["KGE drought"] = per_well(metrics, "test_drought", "KGE").median()
    drought_rmse = per_well(metrics, "test_drought", "RMSE").dropna()
    scores["core wells"] = drought_rmse.index.nunique()
    return scores


def score_cells(scores):
    if scores is None:
        return ("—",) * (len(SCORE_HEADERS) - 1) + ("pending",)
    return (fmt(scores["core wells"]), *(fmt(scores[key], nd=3) for key in METRICS), "scored")


def table(headers, rows):
    lines = ["| " + " | ".join(values) + " |"
             for values in (headers, ("---",) * len(headers), *rows)]
    return "\n".join(lines)


def render(runs, results=RESULTS_DIR):
    scores = {name: read_scores(results / name / "metrics_per_well.csv")
              for name in (*REFERENCES, *(run.name for run in runs))}
    lines = [
        "# Phase 4 absolute scores (v4)", "",
        "Generated by `PFE_DATASET=v4 python -m src.analysis.phase4_overview`. Do not edit by hand.",
        "",
        "Scores are medians across core wells for simulation using the `all` scoring variant. "
        "The well count is the number of core wells with a drought RMSE. A dash marks an "
        "unavailable value. A run is pending when its per-well metrics file is absent.",
        "",
        "R1 uses the full training period. The `_lwo` rows pool predictions from the "
        "five leave-wells-out folds. The `_f25` and `_f50` rows use the most recent 25% and 50% "
        "of the training period. The `_refit` rows fit on training and validation, so any "
        "validation scores for those rows are in-sample. [Phase 4 run plan](phase4_runs.md)",
        "",
        "## References", "",
        "Exploratory scores on the development benchmark.", "",
        table(("Run", *SCORE_HEADERS), [(f"`{name}`", *score_cells(scores[name])) for name in REFERENCES]),
    ]

    best_rows = []
    for block in BLOCKS:
        block_runs = [run for run in runs if run.block == block]
        ordered = sorted(block_runs, key=lambda run: bool(run.suffix))
        rows = [(f"`{run.name}`", run.arm, str(run.reconstruction), run.suffix or "R1",
                 *score_cells(scores[run.name])) for run in ordered]
        lines.extend(("", f"## {block}", "",
                      table(("Run", "Arm", "Pumping reconstruction", "Regime", *SCORE_HEADERS), rows)))

        r1_scores = [(run.name, scores[run.name]["NSE drought"])
                     for run in block_runs if not run.suffix and scores[run.name] is not None]
        best = max(((name, nse) for name, nse in r1_scores if pd.notna(nse)),
                   key=lambda pair: pair[1], default=None)
        if best is None:
            best_rows.append((block, "—" if r1_scores else "pending", "—"))
        else:
            name, nse = best
            best_rows.append((block, f"`{name}`", fmt(nse, nd=3)))

    lines.extend((
        "", "## Best R1 drought NSE per block", "",
        "Picking the best run among many on the test period is descriptive only, so use the "
        "pre-specified contrasts for the Phase 4 results. [Arm contrasts](results_arms_v4.md) "
        "· [Analysis plan §11](analysis_plan.md#11-freeze-and-confirmation-added-in-v2)",
        "", table(("Block", "Run", "Median drought NSE"), best_rows), "",
    ))
    return "\n".join(lines)


def main():
    if DATASET != "v4":
        raise SystemExit("Set PFE_DATASET=v4 to generate the Phase 4 overview.")
    out = ROOT / "docs" / "results_phase4_overview_v4.md"
    out.write_text(render(report_runs(phase4_plan())), encoding="utf-8")
    print(f"-> {out}")


if __name__ == "__main__":
    main()
