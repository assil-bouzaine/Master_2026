"""Check the paper's twin slice macros against the generated Markdown report.

    PYTHONIOENCODING=utf-8 PFE_DATASET=v4 .venv/bin/python -m tests.test_twin_slices_numbers
"""
from pathlib import Path
import re
import subprocess
import sys
from tempfile import TemporaryDirectory
from time import perf_counter

from src.config import ROOT

TOOL = ROOT / "paper" / "tools" / "twin_slices_numbers.py"
FILENAME = "twin_slices_numbers.tex"
PROTOCOLS = {"Free": "free", "Pooled": "pooled_l0.1_fixed3000"}
BASE = "e0.1_u0.3_p0.3_n0.25_rec_base"


def read_macros(path):
    generator, *lines = path.read_text(encoding="utf-8").splitlines()
    assert generator == ("% Generated by PYTHONIOENCODING=utf-8 PFE_DATASET=v4 "
                         ".venv/bin/python paper/tools/twin_slices_numbers.py")
    macros = {}
    for line in lines:
        match = re.fullmatch(r"\\newcommand\{\\(twin[A-Za-z]+)\}\{([+-]?\d+(?:\.\d+)?)\} % (\S.*)", line)
        assert match, line
        name, value, source = match.groups()
        assert name not in macros and "results/v4/twin_" in source, line
        assert "/world_*.json" in source and "twin_report." in source, line
        macros[name] = value
    return macros


def expected_names():
    names = {"twinFPhi", "twinFPilotPhi", "twinFWorlds", "twinFPilotWorlds", "twinFFarShare", "twinFFarCorr"}
    for protocol in PROTOCOLS:
        names.update(f"twinSlice{cell}{metric}{protocol}"
                     for cell in ("G", "I", "O", "S", "Ind", "PLow", "PHigh", "Noise")
                     for metric in ("DC", "TC", "WrongD", "WrongC", "Worlds", "RightPump"))
        names.update(f"twinSlice{metric}{protocol}" for metric in (
            "DCMin", "DCMax", "WrongDTotal", "WorldsTotal", "FalseAlarmDK", "FalseAlarmDN", "PositiveD"))
        names.add(f"twinTauD{protocol}")
        names.update(f"twinF{metric}{protocol}" for metric in (
            "WrongC", "WrongD", "WrongT", "PilotWrongD", "PumpChangeD", "NSEChangeD",
            "TestTwoDetectK", "TestTwoDetectN", "TestTwoFalseK", "TestTwoFalseN"))
    for setting in ("Hard", "None", "Soft"):
        for metric in ("Viol", "CutSign", "DT"):
            names.update((f"twinRQTwoBase{metric}{setting}", f"twinRQTwo{metric}{setting}Min",
                          f"twinRQTwo{metric}{setting}Max"))
    return names


def markdown_table(markdown, heading, field):
    """Find the table with the given column within one report section."""
    level = heading.split()[0]
    section = markdown.split(f"{heading}\n", 1)[1]
    section = re.split(rf"^#{{1,{len(level)}}} ", section, maxsplit=1, flags=re.MULTILINE)[0]
    for block in section.strip().split("\n\n"):
        if not block.startswith("|"):
            continue
        header, _, *rows = ([part.strip() for part in line.strip("|").split("|")]
                            for line in block.splitlines())
        if field in header:
            return [dict(zip(header, row, strict=True)) for row in rows]
    raise AssertionError(f"Missing {field!r} table under {heading!r}")


def compare_with_report(macros):
    markdown = (ROOT / "docs" / "results_twin_v4.md").read_text(encoding="utf-8")
    score_one = markdown_table(markdown,
                               "## Score 1: accuracy against arm C (log RMSE ratio, drought; negative = better than C)",
                               "D / C")
    slice_rates = markdown_table(markdown, "## Score 6: worlds with wrong reasons", "false alarms")
    rq2 = markdown_table(markdown,
                         '### (f) RQ2: hard ("free"), none and soft, base cell and slices one at a time',
                         "sign violations D")
    base_rq2 = {row["setting"]: row for row in rq2 if row["run"] == "twin_rq2" and row["cell"] == BASE}
    main = "e0.1_u0.3_p0.3_n0.25_rec_F2"
    f_heading = f"### twin_shortcut / {main} (φ = 2)"
    f_scores = markdown_table(markdown, f_heading, "score 6")
    f_realised = markdown_table(markdown, f_heading, "far-field variance share")
    pilot = "e0.1_u0.3_p0.3_n0.25_rec_F1"
    pilot_scores = markdown_table(markdown, f"### twin_shortcut_pilot / {pilot} (φ = 1)", "score 6")
    f_changes = markdown_table(markdown, "### Arm D against the base cell", "change in drought NSE")
    f_rates = markdown_table(markdown, "### Shortcut test 2", "false alarms")

    far = f_realised[0]
    expected = {
        "twinFFarShare": format(float(far["far-field variance share"]), ".0%").removesuffix("%"),
        "twinFFarCorr": format(float(far["correlation with local pumping"]), ".2f"),
    }
    for label, setting in (("None", "free_none"), ("Soft", "free_soft1")):
        expected[f"twinRQTwoBaseViol{label}"] = f"{float(base_rq2[setting]['sign violations D'].split()[0]):.0%}"[:-1]
    for protocol, setting in PROTOCOLS.items():
        o = next(row for row in score_one if row["run"] == "twin_slices" and row["cell"].endswith("_rec_O")
                 and row["setting"] == setting)
        for suffix, column in (("DC", "D / C"), ("TC", "T / C (ceiling)")):
            expected[f"twinSliceO{suffix}{protocol}"] = f"{float(o[column].split()[0]):+.3f}"
        for row in f_scores:
            if row["protocol"] == setting:
                wrong, _, worlds = row["score 6"].split()
                expected[f"twinFWrong{row['arm']}{protocol}"] = wrong
                assert macros["twinFWorlds"] == worlds == row["worlds"]
        pilot_d = next(row for row in pilot_scores if row["protocol"] == setting and row["arm"] == "D")
        wrong, _, worlds = pilot_d["score 6"].split()
        expected[f"twinFPilotWrongD{protocol}"] = wrong
        assert macros["twinFPilotWorlds"] == worlds == pilot_d["worlds"]
        change = next(row for row in f_changes if row["protocol"] == setting and row["cell"] == main)
        expected[f"twinFPumpChangeD{protocol}"] = change["change in pumping recovery error"]
        expected[f"twinFNSEChangeD{protocol}"] = change["change in drought NSE"]
        rate = next(row for row in f_rates if row["run"] == "twin_shortcut" and row["arm"] == "D"
                    and row["setting"] == setting)
        k, _, n, *_ = rate["false alarms"].split()
        expected[f"twinFTestTwoFalseK{protocol}"] = k
        expected[f"twinFTestTwoFalseN{protocol}"] = n
        expected[f"twinFTestTwoDetectK{protocol}"] = (rate["detection"].split()[0] if rate["wrong reasons"] != "0" else "0")
        expected[f"twinFTestTwoDetectN{protocol}"] = rate["wrong reasons"]

        slices = [row for row in slice_rates if row["run"] == "twin_slices" and row["setting"] == setting
                  and row["arm"] == "D"]
        assert len(slices) == 8
        expected[f"twinTauD{protocol}"] = slices[0]["τ"]
        for suffix, index in (("K", 0), ("N", 2)):
            expected[f"twinSliceFalseAlarmD{suffix}{protocol}"] = str(
                sum(int(row["false alarms"].split()[index]) for row in slices))
        expected[f"twinSlicePositiveD{protocol}"] = str(sum(int(row["wrong reasons"]) > 0 for row in slices))

    for name, value in expected.items():
        assert macros[name] == value, f"{name}: {macros[name]} (macro), {value} (report)"
    print(f"{len(expected)} macro values match the Markdown report. The F score 6 denominators match too.")


def test_twin_slices_numbers():
    with TemporaryDirectory() as directory:
        first, second = (Path(directory) / name for name in ("first", "second"))
        for target in (first, second):
            subprocess.run([sys.executable, str(TOOL), "--tables-out", str(target)], cwd=ROOT, check=True)
        table = first / FILENAME
        assert table.read_bytes() == (second / FILENAME).read_bytes()
        assert table.read_bytes() == (ROOT / "paper" / "tables" / FILENAME).read_bytes()
        macros = read_macros(table)
        names = expected_names()
        assert macros.keys() == names, (names - macros.keys(), macros.keys() - names)
        compare_with_report(macros)
    print(f"All {len(macros)} expected names are unique and have sources. Both renders match the saved table byte for byte.")


if __name__ == "__main__":
    start = perf_counter()
    test_twin_slices_numbers()
    print(f"test_twin_slices_numbers: all checks passed ({perf_counter() - start:.2f}s)")
